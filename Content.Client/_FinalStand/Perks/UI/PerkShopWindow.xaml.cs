using System.Linq;
using Content.Client._FinalStand.Stylesheets;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._FinalStand.Perks;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._FinalStand.Perks.UI;

[GenerateTypedNameReferences]
public sealed partial class PerkShopWindow : FancyWindow
{
    private FSPerksStateEvent? _state;
    private string? _selectedId;
    private PerkCategory? _filterCategory;
    private string _search = "";

    private int _playerLevel = 1;
    private int _prestigeLevel;

    private readonly IResourceCache _res;
    private readonly IClyde _clyde;

    private readonly Dictionary<string, OwnedTexture> _iconCache = new();

    private readonly Font _fontSmallBold;
    private readonly Font _fontBody;
    private readonly Font _fontBodyBold;
    private readonly Font _fontTitle;
    private readonly Font _fontBig;

    private static readonly Dictionary<PerkCategory, string> CatLabel = new()
    {
        [PerkCategory.Red]    = "OFFENSE",
        [PerkCategory.Blue]   = "DEFENSE",
        [PerkCategory.Green]  = "UTILITY",
        [PerkCategory.Yellow] = "ECONOMY",
        [PerkCategory.Purple] = "HYBRID",
    };

    private static readonly PerkCategory[] CatOrder =
    [
        PerkCategory.Red, PerkCategory.Blue, PerkCategory.Green,
        PerkCategory.Yellow, PerkCategory.Purple,
    ];

    private const int CellSize = 64;
    private const int LoadoutCount = 3;
    private const float CompactBelow = 940f;
    private const float DetailWidth = 340f;

    private bool _compact;
    private float _gridWidth;

    public event Action<FSBuyPerkMessage>? OnBuyPerk;
    public event Action<FSEquipPerkMessage>? OnEquipPerk;
    public event Action<FSUnequipPerkMessage>? OnUnequipPerk;
    public event Action<FSSaveLoadoutMessage>? OnSaveLoadout;
    public event Action<FSLoadLoadoutMessage>? OnLoadLoadout;
    public event Action? OnRespecRequested;
    public event Action? OnPrestigeRequested;

    public PerkShopWindow()
    {
        RobustXamlLoader.Load(this);

        _res   = IoCManager.Resolve<IResourceCache>();
        _clyde = IoCManager.Resolve<IClyde>();

        ((Control)this).Stylesheet = FSMenuStylesheet.Get(
            IoCManager.Resolve<IUserInterfaceManager>(), _res);

        _fontSmallBold = _res.NotoStack("Bold", 10);
        _fontBody      = _res.NotoStack("Regular", 12);
        _fontBodyBold  = _res.NotoStack("Bold", 12);
        _fontTitle     = _res.NotoStack("Bold", 16);
        _fontBig       = _res.NotoStack("Bold", 24);

        ShopTabs.SetTabTitle(0, "Perks");
        ShopTabs.SetTabTitle(1, "Prestige");

        HeaderPanel.PanelOverride = Box(FSUiPalette.BgSurface, FSUiPalette.BgTrack, new Thickness(0, 0, 0, 1));
        FooterPanel.PanelOverride = Box(FSUiPalette.BgRecess, FSUiPalette.BgTrack, new Thickness(0, 1, 0, 0));

        StyleCaption(EquippedTitle);
        StyleCaption(EquippedCountLabel);
        StyleCaption(LoadoutsTitle);
        PpLabel.FontOverride = _fontBig;
        PpLabel.FontColorOverride = FSUiPalette.Currency;
        PpUnitLabel.FontOverride = _fontBodyBold;
        PpUnitLabel.FontColorOverride = FSUiPalette.Currency;
        InvestedLabel.FontColorOverride = FSUiPalette.TextMuted;

        SelectedNameLabel.FontOverride = _fontTitle;
        SelectedNameLabel.FontColorOverride = FSUiPalette.TextPrimary;
        SelectedCategoryLabel.FontOverride = _fontSmallBold;
        SelectedLevelLabel.FontColorOverride = FSUiPalette.TextMuted;
        ShortfallLabel.FontColorOverride = FSUiPalette.StateNegative;

        foreach (var (button, cat) in FilterButtons())
        {
            button.Label.FontOverride = _fontSmallBold;
            button.OnPressed += _ => SetFilter(cat);
        }
        FilterAll.Pressed = true;

        SearchBar.OnTextChanged += _ => { _search = SearchBar.Text; RebuildGrid(); };

        UpgradeButton.Label.FontOverride = _fontBodyBold;
        UpgradeButton.OnPressed += _ =>
        {
            if (_selectedId != null)
                OnBuyPerk?.Invoke(new FSBuyPerkMessage { PerkId = _selectedId });
        };

        EquipButton.Label.FontOverride = _fontSmallBold;
        EquipButton.OnPressed += _ => ToggleEquipSelected();

        RespecButton.Label.FontOverride = _fontSmallBold;
        RespecButton.Label.FontColorOverride = FSUiPalette.StateNegative;
        RespecButton.StyleBoxOverride = Box(FSUiPalette.BgDeep, FSPerkPalette.Edge[PerkCategory.Red], new Thickness(1), 14, 0);
        RespecButton.OnPressed += _ => ShowRespecConfirmation();

        PrestigeButton.OnPressed += _ => ShowPrestigeConfirmation();

        ApplyLayout(false);
        RefreshInfo();
    }

    public void UpdateState(FSPerksStateEvent ev)
    {
        _state = ev;
        PpLabel.Text = ev.PerkPoints.ToString("N0");
        InvestedLabel.Text = $"{Invested(ev.Levels)} PP invested";
        EquippedCountLabel.Text = $"{ev.Slots.Count(s => !string.IsNullOrEmpty(s))} / {FSPerkDef.SlotCount}";
        RebuildLoadouts();
        RebuildSlots();
        RebuildGrid();
        RefreshInfo();
    }

    public void UpdateLeveling(int level, int prestige)
    {
        _playerLevel = level;
        _prestigeLevel = prestige;
        RefreshPrestigeTab();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var compact = Width < CompactBelow;
        if (compact != _compact)
            ApplyLayout(compact);

        var gridWidth = MathF.Max(PerkScroll.Width - 14f, TileWidth);
        if (MathF.Abs(gridWidth - _gridWidth) < 1f)
            return;

        _gridWidth = gridWidth;
        foreach (var grid in _grids)
            grid.MaxGridWidth = _gridWidth;
    }

    // Narrow windows stack the detail panel under the catalogue and split it into two columns.
    private void ApplyLayout(bool compact)
    {
        _compact = compact;
        BodyBox.Orientation = compact ? BoxContainer.LayoutOrientation.Vertical : BoxContainer.LayoutOrientation.Horizontal;
        DetailBox.Orientation = compact ? BoxContainer.LayoutOrientation.Horizontal : BoxContainer.LayoutOrientation.Vertical;
        DetailPanel.SetWidth = compact ? float.NaN : DetailWidth;
        DetailPanel.PanelOverride = Box(FSUiPalette.BgSurface, FSUiPalette.BgTrack,
            compact ? new Thickness(0, 1, 0, 0) : new Thickness(1, 0, 0, 0));
        InfoBox.HorizontalExpand = compact;
        ActionsBox.HorizontalExpand = compact;
        SelectedDescLabel.MaxWidth = compact ? 320 : DetailWidth - 44;
    }

    private void RebuildLoadouts()
    {
        LoadoutRow.RemoveAllChildren();
        if (_state == null)
            return;

        for (var i = 0; i < LoadoutCount; i++)
        {
            var idx = i;
            var loadout = i < _state.Loadouts.Length ? _state.Loadouts[i] : null;
            var used = loadout is { IsEmpty: false };

            var card = new PanelContainer
            {
                HorizontalExpand = true,
                MaxWidth = 250,
                PanelOverride = Box(FSUiPalette.BgSurface, FSUiPalette.BgTrack, new Thickness(1), 10, 8),
            };
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 10 };

            var info = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 4 };
            info.AddChild(new Label
            {
                Text = $"LOADOUT {i + 1}",
                FontOverride = _fontSmallBold,
                FontColorOverride = FSUiPalette.TextPrimary,
            });

            var minis = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 3 };
            for (var s = 0; s < FSPerkDef.SlotCount; s++)
            {
                var id = used ? loadout!.Slots[s] : null;
                minis.AddChild(MiniIcon(id));
            }
            info.AddChild(minis);
            row.AddChild(info);

            var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
            var load = SmallButton("LOAD", !used);
            load.ToolTip = used ? $"Swap to this build ({loadout!.Levels.Count} perks). Your current build is refunded first." : "Nothing saved here";
            load.OnPressed += _ => OnLoadLoadout?.Invoke(new FSLoadLoadoutMessage { LoadoutIndex = idx });
            var buildEmpty = _state.Levels.Count == 0;
            var save = SmallButton("SAVE", buildEmpty);
            save.ToolTip = buildEmpty ? "Your build is empty — nothing to save"
                : used ? "Overwrite with your current build" : "Save your current build here";
            save.OnPressed += _ => OnSaveLoadout?.Invoke(new FSSaveLoadoutMessage { LoadoutIndex = idx });
            buttons.AddChild(load);
            buttons.AddChild(save);
            row.AddChild(buttons);

            card.AddChild(row);
            LoadoutRow.AddChild(card);
        }
    }

    private Control MiniIcon(string? perkId)
    {
        var hasPerk = !string.IsNullOrEmpty(perkId) && FSPerkDef.All.TryGetValue(perkId, out _);
        var panel = new PanelContainer
        {
            SetSize = new System.Numerics.Vector2(20, 20),
            PanelOverride = hasPerk
                ? Box(FSPerkPalette.Background[FSPerkDef.All[perkId!].Category], FSUiPalette.BgTrack, new Thickness(1))
                : Box(FSUiPalette.BgRecess, FSUiPalette.BgTrack, new Thickness(1)),
        };

        if (hasPerk && GetPerkIcon(perkId!) is { } icon)
        {
            panel.AddChild(new TextureRect
            {
                Texture = icon,
                Stretch = TextureRect.StretchMode.Scale,
                SetSize = new System.Numerics.Vector2(16, 16),
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
            });
        }
        return panel;
    }

    private Button SmallButton(string text, bool disabled)
    {
        var button = new Button { Text = text, Disabled = disabled, MinHeight = 24, MinWidth = 56 };
        button.Label.FontOverride = _fontSmallBold;
        button.Label.HorizontalAlignment = HAlignment.Center;
        return button;
    }

    private void StyleCaption(Label label)
    {
        label.FontOverride = _fontSmallBold;
        label.FontColorOverride = FSUiPalette.TextMuted;
    }

    private IEnumerable<(Button, PerkCategory?)> FilterButtons()
    {
        yield return (FilterAll, null);
        yield return (FilterRed, PerkCategory.Red);
        yield return (FilterBlue, PerkCategory.Blue);
        yield return (FilterGreen, PerkCategory.Green);
        yield return (FilterYellow, PerkCategory.Yellow);
        yield return (FilterPurple, PerkCategory.Purple);
    }

    private void SetFilter(PerkCategory? cat)
    {
        _filterCategory = cat;
        foreach (var (button, c) in FilterButtons())
            button.Pressed = c == cat;
        RebuildGrid();
    }

    private void ToggleEquipSelected()
    {
        if (_selectedId == null || _state == null)
            return;

        var equipped = Array.IndexOf(_state.Slots, _selectedId);
        if (equipped >= 0)
        {
            OnUnequipPerk?.Invoke(new FSUnequipPerkMessage { SlotIndex = equipped });
            return;
        }

        var free = Array.FindIndex(_state.Slots, string.IsNullOrEmpty);
        if (free >= 0)
            OnEquipPerk?.Invoke(new FSEquipPerkMessage { PerkId = _selectedId, SlotIndex = free });
    }

    private int Level(string id) => _state?.Levels.TryGetValue(id, out var lvl) == true ? lvl : 0;

    private static int Invested(Dictionary<string, int> levels)
    {
        var total = 0;
        foreach (var level in levels.Values)
            for (var i = 0; i < level; i++)
                total += FSPerkDef.CostForUpgrade(i);
        return total;
    }

    private static StyleBoxFlat Box(Color fill, Color edge, Thickness border, float padX = 0, float padY = 0)
    {
        var box = new StyleBoxFlat { BackgroundColor = fill, BorderColor = edge, BorderThickness = border };
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, padX);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, padY);
        return box;
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (!disposing) return;
        foreach (var tex in _iconCache.Values)
            tex.Dispose();
        _iconCache.Clear();
    }
}
