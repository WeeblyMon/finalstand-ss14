using System.Numerics;
using Content.Client.UserInterface.Systems.Chat.Widgets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Screens;

[GenerateTypedNameReferences]
public sealed partial class DefaultGameScreen : InGameScreen
{
    // Two hand slots plus a gap. HotbarGui centres the hands, so this clears them.
    private const float HandsHalfWidth = 78f;

    // Wide enough to clear AlertsUI's 130px status column in the same corner.
    private const float AlertsClearance = 150f;

    private const int ActionColumns = 6;

    // Matches the 18px XAML margin the hotbar and inventory use to clear the XP bar, plus the 5px
    // screen margin the presets apply.
    private const float BottomBandLift = 23f;

    public DefaultGameScreen()
    {
        RobustXamlLoader.Load(this);

        AutoscaleMaxResolution = new Vector2i(1080, 770);

        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorPreset(ViewportContainer, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(TopLeft, LayoutPreset.TopLeft, margin: 10);
        SetAnchorAndMarginPreset(Ghost, LayoutPreset.BottomWide, margin: 80);
        SetAnchorAndMarginPreset(Hotbar, LayoutPreset.BottomWide, margin: 5);
        SetAnchorAndMarginPreset(Chat, LayoutPreset.TopRight, margin: 10);

        // FINALSTAND: one question per screen region. Status effects are personal condition, so
        // they join the bottom-left survivability corner instead of sharing the top-right with
        // chat and the wave panel. Inventory moves to the bottom right so the equipment strip
        // reads left-to-right as vitals -> hands -> storage.
        SetAnchorAndMarginPreset(Alerts, LayoutPreset.BottomLeft, margin: 5);

        // Just right of the hands, which is where the equipment grid unfolds from when opened. The
        // far-right corner belongs to the quick slots and weapon info, which HotbarGui positions.
        SetAnchorPreset(Inventory, LayoutPreset.CenterBottom);
        SetMarginLeft(Inventory, HandsHalfWidth);
        SetMarginRight(Inventory, HandsHalfWidth);
        SetMarginTop(Inventory, -BottomBandLift);
        SetMarginBottom(Inventory, -BottomBandLift);
        SetGrowHorizontal(Inventory, GrowDirection.End);
        SetGrowVertical(Inventory, GrowDirection.Begin);

        // Six across, wrapping upward. The XAML caps the container at 64px wide for the left-edge
        // column the separated layout still uses, which would squeeze this to one action per row.
        Actions.ActionsContainer.MaxSize = new Vector2(9999, 9999);
        Actions.ActionsContainer.Columns = ActionColumns;
        Actions.ActionsContainer.ExpandBackwards = true;

        SetAnchorPreset(Actions, LayoutPreset.BottomLeft);
        SetMarginLeft(Actions, AlertsClearance);
        SetMarginRight(Actions, AlertsClearance);
        SetMarginTop(Actions, -BottomBandLift);
        SetMarginBottom(Actions, -BottomBandLift);
        SetGrowHorizontal(Actions, GrowDirection.End);
        SetGrowVertical(Actions, GrowDirection.Begin);

        Chat.OnResized += ChatOnResized;
        Chat.OnChatResizeFinish += ChatOnResizeFinish;
    }

    private void ChatOnResizeFinish(Vector2 _)
    {
        var marginBottom = Chat.GetValue<float>(MarginBottomProperty);
        var marginLeft = Chat.GetValue<float>(MarginLeftProperty);
        OnChatResized?.Invoke(new Vector2(marginBottom, marginLeft));
    }

    private void ChatOnResized()
    {
        var marginBottom = Chat.GetValue<float>(MarginBottomProperty);
        SetMarginTop(Alerts, marginBottom);
    }

    public override ChatBox ChatBox => Chat;

    //TODO: There's probably a better way to do this... but this is also the easiest way.
    public override void SetChatSize(Vector2 size)
    {
        SetMarginBottom(Chat, size.X);
        SetMarginLeft(Chat, size.Y);
        SetMarginTop(Alerts, size.X);
    }
}
