    private void BuildStatBars(FSShopWeaponComponent shopComp, EntityUid? weapon, IEntityManager entMan)
    {
        StatBarsContainer.RemoveAllChildren();
        _statBarRefs.Clear();
        _rangedCache = default;

        CritComponent? critComp = null;
        GunComponent? gunComp = null;
        MeleeWeaponComponent? meleeComp = null;
        if (weapon.HasValue)
        {
            entMan.TryGetComponent(weapon.Value, out critComp);
            entMan.TryGetComponent(weapon.Value, out gunComp);
            entMan.TryGetComponent(weapon.Value, out meleeComp);
        }

        EntityPrototype? weaponProto = null;
        GunComponent? gunProto = null;
        MeleeWeaponComponent? meleeProto = null;
        CritComponent? critProto = null;
        if (shopComp.WeaponProtoId is { } weaponProtoId
            && _proto.TryIndex<EntityPrototype>(weaponProtoId, out weaponProto))
        {
            weaponProto.TryGetComponent<GunComponent>(out gunProto, entMan.ComponentFactory);
            weaponProto.TryGetComponent<MeleeWeaponComponent>(out meleeProto, entMan.ComponentFactory);
            weaponProto.TryGetComponent<CritComponent>(out critProto, entMan.ComponentFactory);
        }

        FSGrenadePackComponent? grenadeComp = null;
        FSGrenadePackComponent? grenadeProto = null;
        if (weapon.HasValue)
            entMan.TryGetComponent(weapon.Value, out grenadeComp);
        weaponProto?.TryGetComponent(out grenadeProto, entMan.ComponentFactory);

        var levels = _entityManager.System<FSShopClientSystem>().UpgradeLevels;
        var damageMultiplier = 1.0f;
        var extraPellets = 0;
        var critChanceBonus = 0f;
        var critDamageMult = critComp?.CritMultiplier ?? critProto?.CritMultiplier ?? 1f;
        var attackSpeedMult = 1f;

        foreach (var def in shopComp.Upgrades)
        {
            var level = levels.GetValueOrDefault(def.Id, 0);
            if (level <= 0) continue;
            switch (def.Type)
            {
                case WeaponUpgradeType.Damage:
                    damageMultiplier += level * def.ValuePerLevel;
                    break;
                case WeaponUpgradeType.PelletCount:
                    extraPellets += level * (int)def.ValuePerLevel;
                    break;
                case WeaponUpgradeType.Scrapshot:
                    extraPellets += 3;
                    break;
                case WeaponUpgradeType.CritChance:
                    critChanceBonus = Math.Min(1f, critChanceBonus + level * def.ValuePerLevel);
                    break;
                case WeaponUpgradeType.CritDamage:
                    critDamageMult += level * def.ValuePerLevel;
                    break;
                case WeaponUpgradeType.AttackSpeed:
                    attackSpeedMult += level * def.ValuePerLevel;
                    break;
            }
        }

        // Cache crit values; always valid once BuildStatBars runs.
        _rangedCache.BaseCritChance = critComp?.BaseCritChance ?? critProto?.BaseCritChance ?? 0f;
        _rangedCache.CritChanceBonus = critChanceBonus;
        _rangedCache.CritDamageMult = critDamageMult;
        _rangedCache.Valid = true;

        var isRanged = gunComp != null || gunProto != null;
        var isGrenade = grenadeComp != null || grenadeProto != null;

        if (isRanged)
            BuildRangedStats(shopComp, weapon, weaponProto, gunComp, gunProto, damageMultiplier, extraPellets, entMan);
        else if (isGrenade)
            BuildGrenadeStats(grenadeComp, grenadeProto);
        else if (meleeComp != null || meleeProto != null)
            BuildMeleeStats(meleeComp, meleeProto, damageMultiplier, attackSpeedMult);

        AppendCritStats(critComp, critProto, critChanceBonus, critDamageMult);
    }

    private void BuildRangedStats(FSShopWeaponComponent shopComp, EntityUid? weapon,
        EntityPrototype? weaponProto, GunComponent? gunComp, GunComponent? gunProto,
        float damageMultiplier, int extraPellets, IEntityManager entMan)
    {
        var (damagePerShot, baseDmgPerShot, pellets) = ComputeDamage(shopComp, weapon, weaponProto, damageMultiplier, extraPellets, entMan);
        var basePellets = pellets - extraPellets;

        var augSystem  = _entityManager.System<FSPerkShopSystem>();
        var shopLevels = _entityManager.System<FSShopClientSystem>().UpgradeLevels;

        var spLevel = augSystem.GetSlottedAugmentLevel("StoppingPower");
        var bsLevel = augSystem.GetSlottedAugmentLevel("BulletStorm");
        var augDmgMult = 1f + spLevel * 0.04f;

        // The live weapon carries the server's applied upgrades. Only fall back to the prototype
        // when the player does not hold one yet, and drop the re-derived bonus in that case.
        var hasLiveGun = gunComp != null;
        var baseFireRate = gunComp?.FireRate ?? gunProto?.FireRate ?? 2f;

        var dmgLines = new List<string>();
        var frParts  = new List<string>();
        var accParts = new List<string>();
        var capParts = new List<string>();
        var frBonus  = 0f;

        foreach (var def in shopComp.Upgrades)
        {
            var level = shopLevels.GetValueOrDefault(def.Id, 0);
            if (level <= 0) continue;
            var tag = level > 1 ? $"[{def.Name} ×{level}]" : $"[{def.Name}]";
            switch (def.Type)
            {
                case WeaponUpgradeType.Damage:
                {
                    var bonus = baseDmgPerShot * level * def.ValuePerLevel * basePellets;
                    dmgLines.Add($"{tag}  + {bonus:0.#}");
                    break;
                }
                case WeaponUpgradeType.PelletCount:
                {
                    var bonus = baseDmgPerShot * damageMultiplier * level * (int)def.ValuePerLevel;
                    dmgLines.Add($"{tag}  + {bonus:0.#}");
                    break;
                }
                case WeaponUpgradeType.Scrapshot:
                    dmgLines.Add($"{tag}  + {baseDmgPerShot * damageMultiplier * 3f:0.#}");
                    break;
                case WeaponUpgradeType.FireRate:
                {
                    frBonus += level * def.ValuePerLevel;
                    frParts.Add($"{tag}  + {(int)Math.Round(level * def.ValuePerLevel * 60f)} RPM");
                    break;
                }
                case WeaponUpgradeType.SlamFire:
                case WeaponUpgradeType.FullAuto:
                    frParts.Add(tag);
                    break;
                case WeaponUpgradeType.AngleMax:
                case WeaponUpgradeType.Accuracy:
                {
                    accParts.Add($"{tag}  - {level * AngleDeltaPerLevel(def).Min:0.##}° aimed, - {level * AngleDeltaPerLevel(def).Max:0.##}° max");
                    break;
                }
                case WeaponUpgradeType.MagazineSize:
                {
                    capParts.Add($"{tag}  + {(int)Math.Round(level * def.ValuePerLevel)}");
                    break;
                }
            }
        }

        if (spLevel > 0)
        {
            var spBonus = damagePerShot * pellets * spLevel * 0.04f;
            var spTag = spLevel > 1 ? $"[Stopping Power ×{spLevel}]" : "[Stopping Power]";
            dmgLines.Add($"{spTag}  + {spBonus:0.#}");
        }
        if (bsLevel > 0)
        {
            var bsRpmBonus = (int)Math.Round((hasLiveGun ? baseFireRate : baseFireRate + frBonus) * bsLevel * 0.08f * 60f);
            var bsTag = bsLevel > 1 ? $"[Bullet Storm ×{bsLevel}]" : "[Bullet Storm]";
            frParts.Add($"{bsTag}  + {bsRpmBonus} RPM");
        }

        var weaponProtoId = shopComp.WeaponProtoId?.Id;
        var researchDmg = GetResearchLines(weaponProtoId, FSResearchStatBonusTable.Damage);
        var researchFr = GetResearchLines(weaponProtoId, FSResearchStatBonusTable.FireRate);
        var researchAcc = GetResearchLines(weaponProtoId, FSResearchStatBonusTable.Accuracy);
        var researchCap = GetResearchLines(weaponProtoId, FSResearchStatBonusTable.Capacity);

        // ── Damage ──
        var finalPerShot = damagePerShot * augDmgMult;
        var finalTotal   = finalPerShot * pellets;
        if (finalTotal - baseDmgPerShot * basePellets > 0.01f)
            dmgLines.Add($"= {finalTotal - baseDmgPerShot * basePellets:0.#}");
        dmgLines.AddRange(researchDmg);

        var damageText = pellets > 1 ? $"{finalPerShot:0.#}×{pellets}" : $"{finalPerShot:0.#}";
        StatBarsContainer.AddChild(BuildStatBar("Damage",
            Math.Min(1f, finalTotal / 100f), damageText,
            researchDmg.Count > 0 ? FSUiPalette.StateResearch : dmgLines.Count > 0 ? FSUiPalette.StatePositive : null,
            dmgLines.Count > 0 ? string.Join("\n", dmgLines) : null));

        // ── Fire Rate ──
        // A live weapon already carries every applied upgrade, including the multiplicative ones
        // the breakdown above cannot express. Re-adding frBonus there would double-count.
        var bulletStormMult = 1f + bsLevel * 0.08f;
        var unboostedFireRate = hasLiveGun ? baseFireRate : baseFireRate + frBonus;
        var fireRate = unboostedFireRate * bulletStormMult;
        var rpm = (int)Math.Round(fireRate * 60f);
        if (frParts.Count > 0) frParts.Add($"= {rpm} RPM");
        frParts.AddRange(researchFr);
        StatBarsContainer.AddChild(BuildStatBar("Fire Rate",
            Math.Min(1f, fireRate / 10f), $"{rpm} RPM",
            researchFr.Count > 0 ? FSUiPalette.StateResearch : frParts.Count > 0 ? FSUiPalette.StatePositive : null,
            frParts.Count > 0 ? string.Join("\n", frParts) : null));

        // ── Accuracy ──
        // Sent by the server, which owns the real spread angles. AngleIncrease is not a
        // networked field, so this cannot be derived here.
        var shopAccuracy = _entityManager.System<FSShopClientSystem>().Accuracy;
        var accValue = shopAccuracy >= 0 ? shopAccuracy : shopComp.StatAccuracy;

        if (accParts.Count > 0) accParts.Add($"= {accValue}");
        accParts.AddRange(researchAcc);

        var accFill = accValue / 100f;
        var accText = accValue.ToString();

        StatBarsContainer.AddChild(BuildStatBar("Accuracy",
            accFill, accText,
            researchAcc.Count > 0 ? FSUiPalette.StateResearch : accParts.Count > 0 ? FSUiPalette.StatePositive : null,
            accParts.Count > 0 ? string.Join("\n", accParts) : null));

        // ── Capacity ──
        var (capFill, capText, capRaw) = GetCapacityDisplay(shopComp, weapon, weaponProto, entMan);
        if (capParts.Count > 0) capParts.Add($"= {capText}");
        capParts.AddRange(researchCap);
        StatBarsContainer.AddChild(BuildStatBar("Capacity", capFill, capText,
            researchCap.Count > 0 ? FSUiPalette.StateResearch : capParts.Count > 0 ? FSUiPalette.StatePositive : null,
            capParts.Count > 0 ? string.Join("\n", capParts) : null));

        // Cache everything for hover preview.
        _rangedCache.BaseDmgPerShot    = baseDmgPerShot;
        _rangedCache.BasePellets       = basePellets;
        _rangedCache.ExtraPellets      = extraPellets;
        _rangedCache.DamageMultiplier  = damageMultiplier;
        _rangedCache.AugDmgMult        = augDmgMult;
        _rangedCache.UnboostedFireRate = unboostedFireRate;
        _rangedCache.BulletStormMult   = bulletStormMult;
        _rangedCache.Capacity          = capRaw;
        _rangedCache.IsRanged          = true;
    }

    // What one level takes off each spread angle. Mirrors FSPlayerUpgradesSystem.GunStats.
    private static (float Min, float Max, float Inc) AngleDeltaPerLevel(WeaponUpgradeDef def) => def.Type switch
    {
        WeaponUpgradeType.Accuracy => (def.ValuePerLevel * 0.5f, def.ValuePerLevel * 0.2f, def.ValuePerLevel * 0.3f),
        WeaponUpgradeType.AngleMax => (0f, def.ValuePerLevel, 0f),
        _                          => (0f, 0f, 0f),
    };


    private void BuildMeleeStats(MeleeWeaponComponent? meleeComp, MeleeWeaponComponent? meleeProto,
        float damageMultiplier, float attackSpeedMult)
    {
        var baseDamage = (float)(meleeComp?.Damage ?? meleeProto?.Damage)!.GetTotal();
        baseDamage *= damageMultiplier;
        StatBarsContainer.AddChild(BuildStatBar("Damage", Math.Min(1f, baseDamage / 50f), $"{baseDamage:0.#}"));

        var attackRate = (meleeComp?.AttackRate ?? meleeProto?.AttackRate ?? 1f) * attackSpeedMult;
        var secPerSwing = attackRate > 0f ? 1f / attackRate : 0f;
        StatBarsContainer.AddChild(BuildStatBar("Attack Rate", Math.Min(1f, attackRate / 4f), $"{secPerSwing:F1}s"));

        var range = meleeComp?.Range ?? meleeProto?.Range ?? 1.5f;
        StatBarsContainer.AddChild(BuildStatBar("Range", Math.Min(1f, range / 3f), $"{range:F1}"));
    }

    private void BuildGrenadeStats(FSGrenadePackComponent? live, FSGrenadePackComponent? proto)
    {
        var maxStock    = live?.MaxStock     ?? proto?.MaxStock     ?? 3;
        var regenPerWave = live?.RegenPerWave ?? proto?.RegenPerWave ?? 1;
        var blastBonus   = live?.BlastBonus   ?? proto?.BlastBonus   ?? 0f;
        var burnDuration = live?.BurnDuration ?? proto?.BurnDuration ?? 5f;
        var stunDuration = live?.StunDuration ?? proto?.StunDuration ?? 3f;
        var packType     = live?.PackType     ?? proto?.PackType     ?? GrenadeType.Frag;

        StatBarsContainer.AddChild(BuildStatBar("Capacity", Math.Min(1f, maxStock / 8f), $"{maxStock}"));
        StatBarsContainer.AddChild(BuildStatBar("Regen", Math.Min(1f, regenPerWave / 5f), $"{regenPerWave}/wave"));

        switch (packType)
        {
            case GrenadeType.Flash:
                StatBarsContainer.AddChild(BuildStatBar("Stun", Math.Min(1f, stunDuration / 7f), $"{stunDuration:F0}s"));
                break;
            case GrenadeType.Incendiary:
                StatBarsContainer.AddChild(BuildStatBar("Burn", Math.Min(1f, burnDuration / 15f), $"{burnDuration:F0}s"));
                break;
            default:
                StatBarsContainer.AddChild(BuildStatBar("Blast", Math.Min(1f, (1f + blastBonus) / 2f), $"×{1f + blastBonus:F2}"));
                break;
        }
    }

    private void AppendCritStats(CritComponent? critComp, CritComponent? critProto,
        float critChanceBonus, float critDamageMult)
    {
        var baseCritChance = critComp?.BaseCritChance ?? critProto?.BaseCritChance ?? 0f;
        var critChance     = Math.Min(1f, baseCritChance + critChanceBonus);
        StatBarsContainer.AddChild(BuildStatBar("Crit %", critChance, $"{critChance * 100f:F1}%"));
        StatBarsContainer.AddChild(BuildStatBar("Crit DMG",
            Math.Min(1f, (critDamageMult - 1f) / 2f), $"{critDamageMult:F1}x"));
    }

