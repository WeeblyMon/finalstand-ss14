    }

    public void UpdateState(FSFieldKitStationBuiState state)
    {
        _state = state;
        if (!LabelEdit.HasKeyboardFocus())
            LabelEdit.Text = state.Label;
        RefreshAll();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var satchel = SatchelVolume();
        if (satchel == _satchel)
            return;

        _satchel = satchel;
        RefreshBrewStrip();
    }

    private void RefreshAll()
    {
        BuildBatchRow();
        RefreshBrewStrip();
        RefreshCards();
        RefreshRaw();
        RefreshPackage();
        RefreshSidebar();
    }

    // Satchels the local player carries in hands or inventory, as the server's dump counts them.
    private FixedPoint2 SatchelVolume()
    {
        if (_player.LocalEntity is not { } player)
            return FixedPoint2.Zero;

        var inventory = _entity.System<InventorySystem>();
        var solutions = _entity.System<SharedSolutionContainerSystem>();
        var total = FixedPoint2.Zero;
        foreach (var item in inventory.GetHandOrInventoryEntities(player))
        {
            if (_entity.TryGetComponent<FSHarvestSatchelComponent>(item, out var satchel)
                && solutions.TryGetSolution(item, satchel.Solution, out _, out var solution))
                total += solution.GetTotalPrototypeQuantity(satchel.Reagent);
        }

        return total;
    }

    private FixedPoint2 JugVolume => _state?.Jug?.CurrentVolume ?? FixedPoint2.Zero;
    private FixedPoint2 JugFree => _state?.Jug is { } jug ? jug.MaxVolume - jug.CurrentVolume : FixedPoint2.Zero;

    private void RefreshSidebar()
    {
        var jug = _state?.Jug;
        JugLabel.Text = jug == null ? "none" : $"{jug.CurrentVolume} / {jug.MaxVolume}u";
        FillBar(JugBar, jug, _preview);

        JugRows.RemoveAllChildren();
        if (jug == null)
        {
            JugRows.AddChild(Muted("Put a jug or beaker in the station."));
        }
        else if (jug.Reagents is not { Count: > 0 } reagents)
        {
            JugRows.AddChild(Muted("Empty."));
        }
        else
        {
            foreach (var (reagent, quantity) in reagents)
                JugRows.AddChild(JugRow(reagent.Prototype, quantity));
        }

        EmptyButton.Disabled = jug == null || jug.CurrentVolume <= 0;
        EjectButton.Disabled = jug == null;
        RefreshContext();
    }

    private Control JugRow(string reagent, FixedPoint2 quantity)
    {
        var row = new PanelContainer { MinHeight = 30, PanelOverride = Box(FSUiPalette.BgDeep, FSUiPalette.BgTrack, new Thickness(1), 8, 0) };
        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
        line.AddChild(Swatch(ReagentColor(reagent), 8, 8));
        line.AddChild(new Label { Text = ReagentName(reagent), HorizontalExpand = true, ClipText = true, VerticalAlignment = VAlignment.Center });
        line.AddChild(new Label { Text = $"{quantity}u", FontColorOverride = FSUiPalette.TextMuted, VerticalAlignment = VAlignment.Center });
        var discard = new Button { Text = "✕", MinWidth = 24, StyleBoxOverride = new StyleBoxEmpty(), ToolTip = reagent == TissueReagent ? "Return to the tank" : "Pour away" };
        discard.Label.FontColorOverride = FSUiPalette.TextMuted;
        discard.OnPressed += _ => OnDiscard?.Invoke(reagent);
        line.AddChild(discard);
        row.AddChild(line);
        return row;
    }

    private void RefreshContext()
    {
        ContextBody.RemoveAllChildren();
        switch (Tabs.CurrentTab)
        {
            case BrewTab:
                ContextTitle.Text = "NEXT STOP";
                ContextBody.AddChild(Wrapped(NextStop(), Color.FromHex("#c2beb8")));
                break;
            case RawTab:
                ContextTitle.Text = "THE JUG CAN MAKE";
                PopulateCanMake();
                break;
            default:
                ContextTitle.Text = "MADE THIS SESSION";
                if (_log.Count == 0)
                    ContextBody.AddChild(Muted("Finished items drop on the station."));
                foreach (var entry in _log)
                    ContextBody.AddChild(new Label { Text = entry, FontColorOverride = FSUiPalette.TextMuted });
                break;
        }
    }

    // Reactions the jug already covers, then ones a single missing reagent away, like the old ChemMaster hints.
    private void PopulateCanMake()
    {
        var held = _state?.Jug?.Reagents?.ToDictionary(r => r.Reagent.Prototype, r => r.Quantity) ?? new Dictionary<string, FixedPoint2>();
        if (held.Count == 0)
        {
            ContextBody.AddChild(Muted("Dispense reagents to see what they react into."));
            return;
        }

        var lines = new List<(string Text, bool Ready)>();
        foreach (var reaction in _prototype.EnumeratePrototypes<Content.Shared.Chemistry.Reaction.ReactionPrototype>())
        {
            if (reaction.Reactants.Count == 0 || !reaction.Reactants.Keys.Any(held.ContainsKey))
                continue;

            var missing = reaction.Reactants.Keys.Where(r => !held.ContainsKey(r)).ToList();
            if (missing.Count > 1)
                continue;

            var name = Content.Client.Chemistry.UI.FSFieldKitResolver.NameOf(reaction, _prototype);
            lines.Add(missing.Count == 0 ? (name, true) : ($"{name}: add {ReagentName(missing[0]).ToLowerInvariant()}", false));
        }

        if (lines.Count == 0)
            ContextBody.AddChild(Muted("Nothing this jug is close to making."));
        foreach (var (text, ready) in lines.OrderByDescending(l => l.Ready).Take(8))
            ContextBody.AddChild(Wrapped(text, ready ? OliveText : Color.FromHex("#c2beb8")));
    }

    private string NextStop()
    {
        var volume = JugVolume;
        if (_state?.Jug == null)
            return "Put a jug in the station. A large jug holds a full magazine.";
        if (volume <= 0)
            return "Brew something. A 200u batch fills one syringe magazine.";
        if (volume >= 200)
            return "Load a magazine or fill splash flasks under Package.";
        return $"Split it into {(int) (volume.Float() / 50)} splash flasks under Package, or brew more to fill a magazine.";
    }

    private void RecordMade(string entry)
    {
        _log.Insert(0, entry);
        if (_log.Count > 6)
            _log.RemoveAt(_log.Count - 1);
    }

    // A horizontal stacked bar of the container's reagents, with an optional dashed-looking preview segment.
    private void FillBar(BoxContainer bar, Content.Shared.Chemistry.ContainerInfo? info, (Color Color, FixedPoint2 Volume)? preview)
    {
        bar.RemoveAllChildren();
        var max = info?.MaxVolume.Float() ?? 0f;
        if (max <= 0f)
        {
            bar.AddChild(Segment(FSUiPalette.BgTrack, 1f));
            return;
        }

        var used = 0f;
        foreach (var (reagent, quantity) in info!.Reagents ?? new())
        {
            bar.AddChild(Segment(ReagentColor(reagent.Prototype), quantity.Float() / max));
            used += quantity.Float();
        }

        if (preview is { } p && p.Volume.Float() <= max - used)
        {
            bar.AddChild(Segment(p.Color.WithAlpha(0.45f), p.Volume.Float() / max));
            used += p.Volume.Float();
        }

        bar.AddChild(Segment(FSUiPalette.BgTrack, Math.Max(0f, (max - used) / max)));
    }

    private static PanelContainer Segment(Color color, float ratio) => new()
    {
        HorizontalExpand = true,
        SizeFlagsStretchRatio = Math.Max(ratio, 0.0001f),
        PanelOverride = new StyleBoxFlat { BackgroundColor = color },
    };

    private Color ReagentColor(string reagent)
        => _prototype.TryIndex<ReagentPrototype>(reagent, out var proto) ? proto.SubstanceColor.WithAlpha(1f) : Color.White;

    private string ReagentName(string reagent)
    {
        var name = _prototype.TryIndex<ReagentPrototype>(reagent, out var proto) ? proto.LocalizedName : reagent;
        return name.Length == 0 ? name : name.Substring(0, 1).ToUpperInvariant() + name.Substring(1);
    }

    private static PanelContainer Swatch(Color color, float width, float height) => new()
    {
        SetSize = new Vector2(width, height),
        VerticalAlignment = VAlignment.Center,
        PanelOverride = new StyleBoxFlat { BackgroundColor = color },
    };

    private RichTextLabel Wrapped(string text, Color color, int maxWidth = 250)
    {
        var label = new RichTextLabel { MaxWidth = maxWidth };
        label.SetMessage(Robust.Shared.Utility.FormattedMessage.FromMarkupPermissive(
            $"[color={color.ToHex()}]{Robust.Shared.Utility.FormattedMessage.EscapeText(text)}[/color]"));
        return label;
    }

    private RichTextLabel Muted(string text, int maxWidth = 250) => Wrapped(text, Dim, maxWidth);

    private void Caption(Label label)
    {
        label.FontOverride = _caption;
        label.FontColorOverride = FSUiPalette.TextMuted;
    }

    private Button ActionButton(string text, bool enabled, bool primary, int height = 40)
    {
        var button = new Button { Text = text, Disabled = !enabled, MinHeight = height };
        button.Label.FontOverride = _bold;
        button.Label.HorizontalAlignment = HAlignment.Center;
        button.StyleBoxOverride = !enabled
            ? Box(FSUiPalette.BgElevated, FSUiPalette.BgTrack, new Thickness(1))
            : primary
                ? Box(FSUiPalette.Currency, Color.FromHex("#e3bd70"), new Thickness(1))
                : Box(FSUiPalette.BgPressed, FSUiPalette.BorderSubtle, new Thickness(1));
        button.Label.FontColorOverride = !enabled ? FSUiPalette.TextMuted : primary ? FSUiPalette.BgDeep : FSUiPalette.TextPrimary;
        return button;
    }

    // A toggle-style option: gold edge when selected, like the HUD's chips.
    private ContainerButton Option(string title, string sub, bool selected, bool enabled, Action onPressed, float width = 88)
    {
        var button = new ContainerButton
        {
            MinSize = new Vector2(width, 44),
            Disabled = !enabled,
            StyleBoxOverride = Box(selected ? FSUiPalette.BgPressed : FSUiPalette.BgDeep, selected ? FSUiPalette.Currency : FSUiPalette.BgTrack, new Thickness(1)),
        };
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, VerticalAlignment = VAlignment.Center, HorizontalAlignment = HAlignment.Center };
        box.AddChild(new Label { Text = title, FontOverride = _bold, FontColorOverride = !enabled ? Dim : selected ? FSUiPalette.TextPrimary : FSUiPalette.TextMuted, HorizontalAlignment = HAlignment.Center });
        if (sub.Length > 0)
            box.AddChild(new Label { Text = sub, FontOverride = _caption, FontColorOverride = enabled ? Dim : Research, HorizontalAlignment = HAlignment.Center });
        button.AddChild(box);
        button.OnPressed += _ => onPressed();
        return button;
    }

    private static StyleBoxFlat Box(Color fill, Color edge, Thickness border, float padX = 0, float padY = 0)
    {
        var box = new StyleBoxFlat { BackgroundColor = fill, BorderColor = edge, BorderThickness = border };
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, padX);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, padY);
        return box;
    }
}
