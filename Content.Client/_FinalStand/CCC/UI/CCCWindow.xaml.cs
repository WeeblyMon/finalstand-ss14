using System.Linq;
using Content.Client._FinalStand.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._FinalStand.CCC;
using Content.Shared._FinalStand.GameTicking;
using Content.Shared._FinalStand.Mobs;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._FinalStand.CCC.UI;

[GenerateTypedNameReferences]
public sealed partial class CCCWindow : FancyWindow
{
    public event Action? OnStartWavePressed;
    public event Action<string>? OnBroadcastPressed;

    private readonly IPrototypeManager _protos;
    private readonly IResourceCache _cache;
    private readonly List<string> _shownIconTypes = new();

    public CCCWindow()
    {
        RobustXamlLoader.Load(this);

        ((Control)this).Stylesheet = FSMenuStylesheet.Get(
            IoCManager.Resolve<IUserInterfaceManager>(),
            IoCManager.Resolve<IResourceCache>());
        _protos = IoCManager.Resolve<IPrototypeManager>();
        _cache = IoCManager.Resolve<IResourceCache>();
        StartWaveButton.OnPressed += _ => OnStartWavePressed?.Invoke();
        BroadcastButton.OnPressed += _ =>
        {
            var text = BroadcastInput.Text.Trim();
            if (!string.IsNullOrEmpty(text))
            {
                OnBroadcastPressed?.Invoke(text);
                BroadcastInput.Clear();
            }
        };

        MapViewButton.OnPressed += _ => { MapPanel.Visible = true; PowerPanel.Visible = false; };
        PowerViewButton.OnPressed += _ => { MapPanel.Visible = false; PowerPanel.Visible = true; };
    }

    public void InitMaps(EntityUid? gridUid, EntityUid? powerOwner)
    {
        CccNavMap.MapUid = gridUid;
        CccNavMap.ForceNavMapUpdate();

        CccPowerMap.Owner = powerOwner;
        CccPowerMap.MapUid = gridUid;
        if (powerOwner.HasValue)
            CccPowerMap.ForceNavMapUpdate();
    }

    public void UpdateState(CCCBoundUserInterfaceState state, bool isCaptain)
    {
        WaveNumberLabel.Text = state.WaveNumber.ToString();
        FactionLabel.Text = state.FactionDisplay;
        ModifierLabel.Text = state.WaveModifier;


        var enemyEst = state.IsDarkWave ? "∞" : state.EstimatedEnemyCount.ToString();
        EnemyEstLabel.Text = enemyEst;

        PhaseLabel.Text = state.CurrentPhase == WavePhase.Prep ? "PREP" : "COMBAT";
        PhaseLabel.Modulate = state.CurrentPhase == WavePhase.Prep
            ? FSUiPalette.StatePositive
            : FSUiPalette.StateNegative;

        var mins = (int)state.SecondsToPhaseEnd / 60;
        var secs = (int)state.SecondsToPhaseEnd % 60;
        CountdownLabel.Text = $"{mins}:{secs:D2}";

        AliveLabel.Text = state.AliveEnemyCount.ToString();
        TotalLabel.Text = enemyEst;
        SpawnersLabel.Text = state.ActiveSpawnerDirections;

        var cccHp = Math.Max(0, state.CCCMaxHealth - state.CCCCurrentDamage);
        var cccPct = state.CCCMaxHealth > 0 ? (int)(100f * cccHp / state.CCCMaxHealth) : 0;
        CCCHealthLabel.Text = $"{cccHp} / {state.CCCMaxHealth} ({cccPct}%)";

        var notPrep    = state.CurrentPhase != WavePhase.Prep;
        var notCaptain = !isCaptain;
        StartWaveButton.Disabled = notPrep || notCaptain;
        StartWaveButton.ToolTip = (!notPrep && notCaptain) ? "Only the Captain can start the wave" : null;

        ReadinessLabel.Text = state.TotalPlayerCount > 0
            ? $"{state.ReadiedPlayerCount} / {state.TotalPlayerCount} players ready"
            : "Waiting for players...";
        ReadinessLabel.Modulate = state.ReadiedPlayerCount > 0
            ? FSUiPalette.StatePositive
            : FSUiPalette.TextMuted;

        RebuildZombieIcons(state.NextWaveEnemyTypes);
    }

    private const int IconsPerRow = 4;
    private const float IconGap = 4f;
    private const float IconSize = 64f;

    private void RebuildZombieIcons(List<string> types)
    {
        // State arrives twice a second; the enemy list changes once a wave.
        if (_shownIconTypes.SequenceEqual(types))
            return;

        _shownIconTypes.Clear();
        _shownIconTypes.AddRange(types);

        ZombieIconsContainer.RemoveAllChildren();

        if (types.Count == 0)
        {
            ZombieIconsContainer.Visible = false;
            return;
        }

        var protos = _protos;
        var cache = _cache;
        var anyAdded = false;
        BoxContainer? row = null;

        foreach (var protoId in types)
        {
            if (!protos.TryIndex<EntityPrototype>(protoId, out var proto))
                continue;
            if (!proto.Components.TryGetValue("FSEnemyIcon", out var iconEntry)
                || iconEntry.Component is not FSEnemyIconComponent iconComp
                || string.IsNullOrEmpty(iconComp.IconPath))
                continue;
            if (!cache.TryGetResource<TextureResource>(iconComp.IconPath, out var texRes))
                continue;

            var displayName = proto.Name.Length > 0
                ? new string(char.ToUpperInvariant(proto.Name[0]), 1) + proto.Name.Substring(1)
                : protoId;

            if (row == null || row.ChildCount >= IconsPerRow)
            {
                row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 0, 0, 4) };
                ZombieIconsContainer.AddChild(row);
            }

            row.AddChild(new TextureRect
            {
                Texture = texRes.Texture,
                SetWidth = IconSize,
                SetHeight = IconSize,
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                ToolTip = displayName,
                Margin = new Thickness(0, 0, IconGap, 0),
            });
            anyAdded = true;
        }

        ZombieIconsContainer.Visible = anyAdded;
    }

}
