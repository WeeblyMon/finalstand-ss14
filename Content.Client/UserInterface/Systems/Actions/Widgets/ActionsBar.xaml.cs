using System.Numerics;
using Content.Client._FinalStand.Interface;
using Content.Client.UserInterface.Systems.Actions.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Actions.Widgets;

[GenerateTypedNameReferences]
public sealed partial class ActionsBar : UIWidget
{
    // FINALSTAND: the bar owns its own geometry so the panels that dodge it cannot drift out of
    // step with it. Columns at SlotSize, plus grid gaps, the panel content margin and its border.
    public const int Columns = 9;
    private const int GridGap = 4;
    private const int PanelMargin = 8;
    private const int PanelMarginVertical = 7;

    private const int ArrowWidth = 18;

    public const float BarWidth =
        ActionButton.SlotSize * Columns + GridGap * (Columns - 1) + PanelMargin * 2 + 2
        + (ArrowWidth + GridGap) * 2;

    public const float BarHeight = ActionButton.SlotSize + PanelMarginVertical * 2 + 2;

    public ActionsBar()
    {
        RobustXamlLoader.Load(this);
        ActionsPanel.PanelOverride = FSHudStyle.ModulePanel();

        // Always drawn, disabled when there is nowhere to page. Hiding them would change the bar's
        // width as actions come and go, and BarWidth is what the neighbouring panels dodge.
        foreach (var arrow in new[] { PrevPage, NextPage })
        {
            arrow.MinSize = new Vector2(ArrowWidth, ActionButton.SlotSize);
            FSHudStyle.StyleButton(arrow, padX: 2, padY: 0);
        }
    }

    public void SetPagingEnabled(bool prev, bool next)
    {
        PrevPage.Disabled = !prev;
        NextPage.Disabled = !next;

        PrevPage.Label.FontColorOverride = prev ? FSPalette.TextBright : FSPalette.TextDim;
        NextPage.Label.FontColorOverride = next ? FSPalette.TextBright : FSPalette.TextDim;
    }
}
