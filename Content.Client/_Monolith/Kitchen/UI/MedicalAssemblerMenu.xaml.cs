using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Monolith.Kitchen.UI;

[GenerateTypedNameReferences]
public sealed partial class MedicalAssemblerMenu : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;

    public bool IsBusy;
    public TimeSpan CurrentAssembleTimeEnd;

    public MedicalAssemblerMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void ToggleBusy(bool busy)
    {
        DisableOverlay.Visible = busy;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!IsBusy)
        {
            CookTimeInfoLabel.Text = string.Empty;
            return;
        }

        if (CurrentAssembleTimeEnd > _timing.CurTime)
        {
            CookTimeInfoLabel.Text = Loc.GetString("medical-assembler-time-label",
                ("time", (int) CurrentAssembleTimeEnd.Subtract(_timing.CurTime).TotalSeconds));
        }
    }
}
