namespace Content.Client._FinalStand.Shop.UI;

[GenerateTypedNameReferences]
public sealed partial class WeaponShopWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IUserInterfaceManager _uiManager = default!;
    [Dependency] private IResourceCache _resourceCache = default!;

    public event Action? OnBuyPressed;
    public event Action<string>? OnUpgradePressed;
    public event Action? OnSellConfirmed;

    private int _price;
    private EntProtoId? _weaponProtoId;
    private bool _isGrenadePackShop;
    private bool _singlePurchase;
    private bool _owned;
    private int _credits;

    private List<WeaponUpgradeDef> _defs = new();
    private Dictionary<string, int> _levels = new();

    private bool _inConfirmState;
    private float _confirmTimer;
    private int _sellRefund;
    private const float ConfirmTimeout = 4f;
    private const int BarSegments = 14;
    private const float MinCardWidth = 290f;

    private int _columns;

    private readonly Font _fontCaption;
    private readonly Font _fontBody;
    private readonly Font _fontBold;
    private readonly Font _fontTitle;
    private readonly Font _fontValue;

    private sealed class StatBarRefs
    {
        public required PanelContainer[] Segments;
        public required Label ValueLabel;
        public float BaseFill;
        public string BaseText = "";
        public Color? BaseColor;
    }

    private readonly Dictionary<string, StatBarRefs> _statBarRefs = new();

    private struct RangedStatCache
    {
        public float BaseDmgPerShot;
        public int   BasePellets;
        public int   ExtraPellets;
        public float DamageMultiplier;
        public float AugDmgMult;
        public float UnboostedFireRate; // baseFireRate + frBonus (pre-BulletStorm)
        public float BulletStormMult;
        public int   Capacity;          // -1 = battery / infinite
        public float BaseCritChance;
        public float CritChanceBonus;
        public float CritDamageMult;
        public bool  Valid;
        public bool  IsRanged;
    }

    private RangedStatCache _rangedCache;

    public WeaponShopWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        ((Control)this).Stylesheet = FSMenuStylesheet.Get(_uiManager, _resourceCache);

        _fontCaption = _resourceCache.NotoStack("Bold", 9);
        _fontBody    = _resourceCache.NotoStack("Regular", 11);
        _fontBold    = _resourceCache.NotoStack("Bold", 11);
        _fontTitle   = _resourceCache.NotoStack("Bold", 17);
        _fontValue   = _resourceCache.NotoStack("Bold", 12);

        BannerPanel.PanelOverride = Box(FSUiPalette.BgSurface, FSUiPalette.BgTrack, new Thickness(0, 0, 0, 1));
        SpriteFrame.PanelOverride = Box(FSUiPalette.BgRecess, FSUiPalette.BgTrack, new Thickness(1));

        WeaponNameLabel.FontOverride = _fontTitle;
        WeaponNameLabel.FontColorOverride = FSUiPalette.TextPrimary;
        OwnedChipLabel.FontOverride = _fontCaption;
        CategoryLabel.FontColorOverride = FSUiPalette.TextMuted;
        Caption(UpgradesTitle);
        Caption(BalanceTitle);
        UpgradeCounterLabel.FontColorOverride = Color.FromHex("#6a6761");
        NotOwnedLabel.FontColorOverride = FSUiPalette.StatePending;
        BalanceLabel.FontOverride = _fontTitle;
        BalanceLabel.FontColorOverride = FSUiPalette.Currency;
        SellConfirmLabel.FontColorOverride = FSUiPalette.TextPrimary;

        BuyButton.Label.FontOverride = _fontBold;
        BuyButton.Label.HorizontalAlignment = HAlignment.Center;
        SellButton.Label.FontOverride = _fontCaption;
        KeepButton.Label.FontOverride = _fontCaption;

        BuyButton.OnPressed += _ => OnBuyPressed?.Invoke();

        SellButton.OnPressed += _ =>
        {
            if (_inConfirmState)
            {
                OnSellConfirmed?.Invoke();
                ExitConfirmState();
            }
            else
            {
                EnterConfirmState();
            }
        };
        KeepButton.OnPressed += _ => ExitConfirmState();

        ExitConfirmState();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_confirmTimer > 0f)
        {
            _confirmTimer -= args.DeltaSeconds;
            if (_confirmTimer <= 0f)
                ExitConfirmState();
        }

        var columns = Math.Max(1, (int)((UpgradesScroll.Width - 14f + 10f) / (MinCardWidth + 10f)));
        if (columns != _columns && UpgradesScroll.Width > 0)
        {
            _columns = columns;
            UpgradesContainer.Columns = columns;
            RebuildCards();
        }
    }

    public void Populate(EntityUid shopEntity, IEntityManager entMan)
    {
        if (!entMan.TryGetComponent<FSShopWeaponComponent>(shopEntity, out var comp))
            return;

        _price = comp.Price;
        _weaponProtoId = comp.WeaponProtoId;
        _singlePurchase = comp.SinglePurchase;
        _isGrenadePackShop = _weaponProtoId is { } pid
            && _proto.TryIndex<EntityPrototype>(pid, out var wEntProto)
            && wEntProto.TryGetComponent<FSGrenadePackComponent>(out _, _entityManager.ComponentFactory);

        var meta = entMan.GetComponent<MetaDataComponent>(shopEntity);
        WeaponNameLabel.Text = Capitalize(meta.EntityName);
        CategoryLabel.Text = comp.Category;
        DescLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            $"[color={Color.FromHex("#a9a59f").ToHex()}]{FormattedMessage.EscapeText(meta.EntityDescription)}[/color]"));
        WeaponSprite.SetEntity(shopEntity);

        var shopClient = _entityManager.System<FSShopClientSystem>();
        BuildStatBars(comp, shopClient.FindOwnedWeapon(comp.WeaponProtoId), entMan);
        RefreshUpgrades(comp.Upgrades, shopClient.UpgradeLevels, shopClient.CurrentCredits);
        UpdateBalance(shopClient.CurrentCredits);
    }

    public void UpdateBalance(int credits)
    {
        _credits = credits;
        BalanceLabel.Text = Money(credits);
        RefreshBuyButton();
        RebuildCards();
    }

    public void UpdateWeaponTitle(string title)
    {
        if (title.Length > 0)
            WeaponNameLabel.Text = Capitalize(title);
    }

    public void RefreshStatBars(FSShopWeaponComponent comp, EntityUid? gun, IEntityManager entMan)
    {
        BuildStatBars(comp, gun, entMan);
    }

    public void UpdateSellButton(int refund, bool hasWeapon)
    {
        _sellRefund = refund;
        _owned = hasWeapon;

        OwnedChipLabel.Text = hasWeapon ? "OWNED" : "NOT OWNED";
        OwnedChipLabel.FontColorOverride = hasWeapon ? FSPerkPalette.Accent[PerkCategory.Green] : FSUiPalette.TextMuted;
        OwnedChip.PanelOverride = hasWeapon
            ? Box(FSPerkPalette.Background[PerkCategory.Green], FSPerkPalette.Edge[PerkCategory.Green], new Thickness(1))
            : Box(Color.Transparent, FSUiPalette.BorderNeutral, new Thickness(1));

        SellButton.Visible = hasWeapon;
        NotOwnedLabel.Visible = !hasWeapon;
        NotOwnedLabel.Text = $"· Buy and carry the {WeaponNameLabel.Text} to upgrade it";
        if (!_inConfirmState)
            ExitConfirmState();

        RefreshBuyButton();
        RebuildCards();
    }

    public void ResetConfirmation()
    {
        if (_inConfirmState)
            ExitConfirmState();
    }

    public void RefreshUpgrades(List<WeaponUpgradeDef> defs, Dictionary<string, int> levels, int credits)
    {
        _defs = defs;
        _levels = levels;
        _credits = credits;
        RebuildCards();
    }

    private void RefreshBuyButton()
    {
        var shopClient = _entityManager.System<FSShopClientSystem>();
        var alreadyHeld = (_isGrenadePackShop || _singlePurchase)
            && shopClient.PlayerHasWeaponInInventory(shopClient.GetLocalPlayer(), _weaponProtoId);

        BuyButton.Visible = !alreadyHeld;
        if (alreadyHeld)
            return;

        var afford = _credits >= _price;
        BuyButton.Disabled = !afford;
        BuyButton.Text = !afford ? $"{Money(_price)} · {Money(_price - _credits)} SHORT"
            : _owned ? $"BUY ANOTHER · {Money(_price)}"
            : $"BUY · {Money(_price)}";

        // Only the first purchase is the window's primary action.
        var primary = afford && !_owned;
        BuyButton.StyleBoxOverride = primary
            ? Box(FSUiPalette.Currency, Color.FromHex("#e3bd70"), new Thickness(1))
            : Box(FSUiPalette.BgElevated, FSUiPalette.BorderNeutral, new Thickness(1));
        BuyButton.Label.FontColorOverride = primary ? FSUiPalette.BgDeep : afford ? FSUiPalette.TextPrimary : FSUiPalette.TextMuted;
    }

    private void EnterConfirmState()
    {
        _inConfirmState = true;
        _confirmTimer = ConfirmTimeout;
        SellButton.Text = $"CONFIRM SELL · {Money(_sellRefund)}";
        SellButton.StyleBoxOverride = Box(Color.FromHex("#b3402f"), FSUiPalette.StateNegative, new Thickness(1), 10, 0);
        SellButton.Label.FontColorOverride = Color.White;
        KeepButton.Visible = true;
    }

    private void ExitConfirmState()
    {
        _inConfirmState = false;
        _confirmTimer = 0f;
        SellButton.Text = $"SELL · {Money(_sellRefund)}";
        SellButton.StyleBoxOverride = Box(FSUiPalette.BgDeep, FSUiPalette.BorderNeutral, new Thickness(1), 10, 0);
        SellButton.Label.FontColorOverride = FSUiPalette.TextMuted;
        SellButton.ToolTip = "Refunds 40% of the price and 40% of what you spent upgrading it.";
        KeepButton.Visible = false;
    }

    private void Caption(Label label)
    {
        label.FontOverride = _fontCaption;
        label.FontColorOverride = FSUiPalette.TextMuted;
    }

    private static string Money(int amount) => $"${amount:N0}";

    private static StyleBoxFlat Box(Color fill, Color edge, Thickness border, float padX = 0, float padY = 0)
    {
        var box = new StyleBoxFlat { BackgroundColor = fill, BorderColor = edge, BorderThickness = border };
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, padX);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, padY);
        return box;
    }
}
