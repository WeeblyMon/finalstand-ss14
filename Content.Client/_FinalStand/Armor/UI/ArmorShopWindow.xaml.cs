using Content.Shared._FinalStand.Armor.Shop;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._FinalStand.Armor.UI;

[GenerateTypedNameReferences]
public sealed partial class ArmorShopWindow : DefaultWindow
{
    public event Action<string>? OnBuyPressed;

    private FSArmorShopState? _state;
    private string? _selectedTierId;

    private static readonly Color ColorEquipped   = Color.FromHex("#69F0AE");
    private static readonly Color ColorAffordable = Color.FromHex("#EBCB8B");
    private static readonly Color ColorTooExpensive = Color.FromHex("#BF616A");
    private static readonly Color ColorMuted      = Color.FromHex("#AAAAAA");
    private static readonly Color ColorGreen      = Color.FromHex("#69F0AE");
    private static readonly Color ColorRed        = Color.FromHex("#BF616A");

    public ArmorShopWindow()
    {
        RobustXamlLoader.Load(this);
        BuyButton.OnPressed += _ =>
        {
            if (_selectedTierId != null)
                OnBuyPressed?.Invoke(_selectedTierId);
        };
    }

    public void Populate(FSArmorShopState state)
    {
        _state = state;

        TierListContainer.DisposeAllChildren();
        foreach (var tier in FSArmorShopDefs.Tiers)
            TierListContainer.AddChild(BuildTierRow(tier));

        // Show equipped tier on open, else first tier.
        var toShow = state.EquippedTierId != null
            ? FSArmorShopDefs.GetTier(state.EquippedTierId)
            : FSArmorShopDefs.Tiers.Count > 0 ? FSArmorShopDefs.Tiers[0] : null;
        if (toShow != null) SelectTier(toShow);
    }

    private Control BuildTierRow(FSArmorTierDef tier)
    {
        var state = _state;
        var isEquipped = tier.Id == state?.EquippedTierId;
        var canAfford = CanAffordTier(tier);

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 0, 0, 4),
        };

        var btn = new Button
        {
            Text = tier.Name,
            HorizontalExpand = true,
            MinWidth = 170,
        };
        btn.Modulate = Color.FromHex("#C5E1A5");
        btn.OnPressed += _ => SelectTier(tier);
        row.AddChild(btn);

        var statusLabel = new Label
        {
            HorizontalExpand = false,
            HorizontalAlignment = HAlignment.Right,
            Margin = new Thickness(6, 0, 0, 0),
        };
        if (isEquipped)
        {
            statusLabel.Text = "EQUIPPED";
            statusLabel.Modulate = ColorEquipped;
        }
        else
        {
            statusLabel.Text = $"${tier.Price:N0}";
            statusLabel.Modulate = canAfford ? ColorAffordable : ColorTooExpensive;
        }
        row.AddChild(statusLabel);
        return row;
    }

    private void SelectTier(FSArmorTierDef tier)
    {
        _selectedTierId = tier.Id;
        SelectedTierName.Text = tier.Name;

        StatsContainer.DisposeAllChildren();

        void AddRow(string label, string value, Color valueColor)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 1, 0, 1),
            };
            row.AddChild(new Label { Text = label, HorizontalExpand = true, Modulate = ColorMuted });
            row.AddChild(new Label { Text = value, Modulate = valueColor });
            StatsContainer.AddChild(row);
        }

        AddRow("Blunt:",     $"-{tier.Blunt     * 100:0}%", ColorGreen);
        AddRow("Slash:",     $"-{tier.Slash     * 100:0}%", ColorGreen);
        AddRow("Piercing:",  $"-{tier.Piercing  * 100:0}%", ColorGreen);
        AddRow("Heat:",      $"-{tier.Heat      * 100:0}%", ColorGreen);
        if (tier.Radiation > 0f)
            AddRow("Radiation:", $"-{tier.Radiation * 100:0}%", ColorGreen);
        AddRow("Caustic:",   $"-{tier.Caustic   * 100:0}%", ColorGreen);
        AddRow("Shock:",     $"-{tier.Shock     * 100:0}%", ColorGreen);
        AddRow("Explosion:", $"-{tier.Explosion * 100:0}%", ColorGreen);

        var speedPct   = tier.SpeedMod * 100f;
        var speedText  = speedPct >= 0f ? $"+{speedPct:0}%" : $"{speedPct:0}%";
        AddRow("Speed:", speedText, tier.SpeedMod >= 0f ? ColorGreen : ColorRed);

        if (tier.StaminaReduction > 0f)
            AddRow("Stamina resist:", $"-{tier.StaminaReduction * 100:0}%", ColorGreen);

        StatsContainer.AddChild(new Control { MinHeight = 6 }); // spacer

        var equippedTier = _state?.EquippedTierId != null ? FSArmorShopDefs.GetTier(_state.EquippedTierId) : null;
        var refund = equippedTier?.Price / 2 ?? 0;
        if (refund > 0)
            AddRow("Refund on current:", $"${refund:N0}", ColorAffordable);
        var netCost = tier.Price - refund;
        AddRow("Net cost:", $"${netCost:N0}", ColorAffordable);

        var isEquipped = tier.Id == _state?.EquippedTierId;
        BuyButton.Disabled = isEquipped || !CanAffordTier(tier);
    }

    private bool CanAffordTier(FSArmorTierDef tier)
    {
        if (_state == null) return false;
        var equippedTier = _state.EquippedTierId != null ? FSArmorShopDefs.GetTier(_state.EquippedTierId) : null;
        var refund = equippedTier?.Price / 2 ?? 0;
        return _state.Credits >= tier.Price - refund;
    }
}
