using Content.Shared._FinalStand.CCC;
using Content.Shared._FinalStand.GameTicking;
using Content.Shared._FinalStand.ReadyCheck;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._FinalStand.CCC.UI;

[GenerateTypedNameReferences]
public sealed partial class CCCWindow : DefaultWindow
{
    public event Action? OnStartWavePressed;
    public event Action<string>? OnBroadcastPressed;

    public CCCWindow()
    {
        RobustXamlLoader.Load(this);
        StartWaveButton.OnPressed += _ => OnStartWavePressed?.Invoke();
        BroadcastButton.OnPressed += _ =>
        {
            var text = BroadcastInput.Text.Trim();
            if (!string.IsNullOrEmpty(text))
            {
                OnBroadcastPressed?.Invoke(text);
                BroadcastInput.Clear();
            }
        };
    }

    public void UpdateState(CCCBoundUserInterfaceState state)
    {
        WaveNumberLabel.Text = state.WaveNumber.ToString();
        FactionLabel.Text = state.FactionDisplay;
        ModifierLabel.Text = state.WaveModifier;
        EnemyEstLabel.Text = state.EstimatedEnemyCount.ToString();

        PhaseLabel.Text = state.CurrentPhase == WavePhase.Prep ? "PREP" : "COMBAT";
        PhaseLabel.Modulate = state.CurrentPhase == WavePhase.Prep
            ? Color.FromHex("#AAFFAA")
            : Color.FromHex("#FF8888");

        var mins = (int)state.SecondsToPhaseEnd / 60;
        var secs = (int)state.SecondsToPhaseEnd % 60;
        CountdownLabel.Text = $"{mins}:{secs:D2}";

        AliveLabel.Text = state.AliveEnemyCount.ToString();
        TotalLabel.Text = state.EstimatedEnemyCount.ToString();
        SpawnersLabel.Text = state.ActiveSpawnerCount.ToString();

        StartWaveButton.Disabled = state.CurrentPhase != WavePhase.Prep;

        RebuildDeptGrid(state.DepartmentStatus);
    }

    private void RebuildDeptGrid(Dictionary<string, ReadyStatus> statuses)
    {
        DeptContainer.RemoveAllChildren();
        foreach (var (code, status) in statuses)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };

            var codeLabel = new Label
            {
                Text = code,
                SetWidth = 48,
                Modulate = Color.FromHex("#DDDDDD"),
            };

            var (statusText, statusColor) = status switch
            {
                ReadyStatus.Ready    => ("READY",    "#44FF44"),
                ReadyStatus.NotReady => ("NOT RDY",  "#FF4444"),
                _                   => ("NO RESP",  "#888888"),
            };

            var statusLabel = new Label
            {
                Text = statusText,
                Modulate = Color.FromHex(statusColor),
            };

            row.AddChild(codeLabel);
            row.AddChild(statusLabel);
            DeptContainer.AddChild(row);
        }
    }
}
