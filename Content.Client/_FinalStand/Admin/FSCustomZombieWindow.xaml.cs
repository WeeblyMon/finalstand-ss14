using System.Linq;
using System.Numerics;
using Content.Shared._FinalStand.Admin;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._FinalStand.Admin;

[GenerateTypedNameReferences]
[UsedImplicitly]
public sealed partial class FSCustomZombieWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _protoManager = default!;

    private readonly List<string> _zombieIds = new();
    private readonly List<(FSZombieFieldInfo Info, FloatSpinBox Box)> _fieldRows = new();

    public event Action<string>? OnZombieSelected;
    public event Action<string>? OnSpawnRequested;

    public FSCustomZombieWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ZombieOption.OnItemSelected += args =>
        {
            ZombieOption.SelectId(args.Id);
            if (TryGetSelectedProto(out var protoId))
                OnZombieSelected?.Invoke(protoId);
        };

        SpawnButton.OnPressed += _ =>
        {
            if (TryGetSelectedProto(out var protoId))
                OnSpawnRequested?.Invoke(protoId);
        };

        PopulateZombieOptions();
    }

    private void PopulateZombieOptions()
    {
        _zombieIds.Clear();
        ZombieOption.Clear();

        var protos = _protoManager.EnumeratePrototypes<EntityPrototype>()
            .Where(p => !p.Abstract && p.ID.StartsWith("FSZombie"))
            .OrderBy(p => p.ID);

        foreach (var proto in protos)
        {
            _zombieIds.Add(proto.ID);
            ZombieOption.AddItem(proto.ID);
        }

        if (_zombieIds.Count > 0)
            ZombieOption.SelectId(0);
    }

    public bool TryGetSelectedProto(out string protoId)
    {
        protoId = string.Empty;
        var id = ZombieOption.SelectedId;
        if (id < 0 || id >= _zombieIds.Count)
            return false;

        protoId = _zombieIds[id];
        return true;
    }

    public void LoadFields(FSCustomZombieEuiMsg.FieldData data)
    {
        if (!TryGetSelectedProto(out var selected) || selected != data.ProtoId)
            return;

        HealthBox.Value = data.Health;
        WalkBox.Value = data.WalkSpeed;
        SprintBox.Value = data.SprintSpeed;
        DamageBox.Value = 1f;
        ScaleBox.Value = 1f;
        ResistBox.Value = 1f;

        _fieldRows.Clear();
        FieldsContainer.RemoveAllChildren();

        var grouped = data.Fields.GroupBy(f => f.Component).OrderBy(g => g.Key);

        foreach (var group in grouped)
        {
            FieldsContainer.AddChild(new Label
            {
                Text = group.Key,
                Margin = new Thickness(0, 6, 0, 2),
            });

            foreach (var info in group)
            {
                var box = new FloatSpinBox(0.1f, 3)
                {
                    Value = info.Value,
                    HorizontalExpand = true,
                };

                var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
                row.AddChild(new Label { Text = info.Field, MinSize = new Vector2(190, 0) });
                row.AddChild(box);

                FieldsContainer.AddChild(row);
                _fieldRows.Add((info, box));
            }
        }

        if (_fieldRows.Count == 0)
        {
            FieldsContainer.AddChild(new Label
            {
                Text = "This zombie has no tunable ability variables.",
                Margin = new Thickness(0, 4, 0, 0),
            });
        }
    }

    public void SetStatus(string text)
    {
        StatusLabel.Text = text;
    }

    public FSCustomZombieEuiMsg.SpawnRequest? BuildRequest()
    {
        if (!TryGetSelectedProto(out var protoId))
            return null;

        var req = new FSCustomZombieEuiMsg.SpawnRequest
        {
            ProtoId = protoId,
            Health = HealthBox.Value,
            DamageMultiplier = DamageBox.Value,
            WalkSpeed = WalkBox.Value,
            SprintSpeed = SprintBox.Value,
            Scale = ScaleBox.Value,
            DamageTakenMultiplier = ResistBox.Value,
        };

        foreach (var (info, box) in _fieldRows)
        {
            if (Math.Abs(box.Value - info.Value) < 0.0001f)
                continue;

            req.Overrides.Add(new FSZombieFieldOverride
            {
                Component = info.Component,
                Field = info.Field,
                Value = box.Value,
            });
        }

        return req;
    }
}
