using Content.Shared._FinalStand.CashTransfer;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._FinalStand.CashTransfer.UI;

[GenerateTypedNameReferences]
public sealed partial class CashTransferWindow : DefaultWindow
{
    public event Action<int>? OnTransferConfirmed;

    private const int MaxDigits = 9;

    public CashTransferWindow()
    {
        RobustXamlLoader.Load(this);

        AmountInput.IsValid = IsAmountValid;

        ConfirmButton.OnPressed += _ =>
        {
            if (!int.TryParse(AmountInput.Text, out var amount) || amount <= 0)
                return;

            ConfirmButton.Disabled = true;
            OnTransferConfirmed?.Invoke(amount);
        };

        CancelButton.OnPressed += _ => Close();
    }

    private static bool IsAmountValid(string text)
    {
        if (text.Length > MaxDigits)
            return false;

        foreach (var c in text)
        {
            if (!char.IsDigit(c))
                return false;
        }

        return true;
    }

    public void UpdateState(FSCashTransferBuiState state)
    {
        ToLabel.Text = $"To: {state.TargetName}";
        BalanceLabel.Text = $"Balance: {state.SenderBalance} credits";
        ConfirmButton.Disabled = false;
    }
}
