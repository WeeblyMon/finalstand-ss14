[GenerateTypedNameReferences]
public sealed partial class PerkShopWindow : FancyWindow
{
    private FSPerksStateEvent? _state;
    private string? _selectedId;
    private int? _selectedSlot;
    private PerkCategory? _filterCategory;
    private string _search = "";

    private int _playerLevel = 1;
    private int _prestigeLevel;

    private readonly IResourceCache _res;
    private readonly IClyde _clyde;

    private readonly Dictionary<string, OwnedTexture> _iconCache = new();

    private static readonly Dictionary<PerkCategory, Color> CatBg = new()
    {
        [PerkCategory.Red]    = Color.FromHex("#1A0000"),
        [PerkCategory.Blue]   = Color.FromHex("#00011A"),
        [PerkCategory.Green]  = Color.FromHex("#142400"),
        [PerkCategory.Yellow] = Color.FromHex("#242100"),
        [PerkCategory.Purple] = Color.FromHex("#160024"),
    };

    private static readonly Dictionary<PerkCategory, Color> CatAccent = new()
    {
        [PerkCategory.Red]    = Color.FromHex("#FF5252"),
        [PerkCategory.Blue]   = Color.FromHex("#4FC3F7"),
        [PerkCategory.Green]  = Color.FromHex("#69F0AE"),
        [PerkCategory.Yellow] = Color.FromHex("#FFD740"),
        [PerkCategory.Purple] = Color.FromHex("#CE93D8"),
    };

    private static readonly Dictionary<PerkCategory, string> CatLabel = new()
    {
        [PerkCategory.Red]    = "OFFENSE",
        [PerkCategory.Blue]   = "DEFENSE",
        [PerkCategory.Green]  = "UTILITY",
        [PerkCategory.Yellow] = "ECONOMY",
        [PerkCategory.Purple] = "HYBRID",
    };

    private static readonly PerkCategory[] CatOrder =
    [
        PerkCategory.Red, PerkCategory.Blue, PerkCategory.Green,
        PerkCategory.Yellow, PerkCategory.Purple,
    ];

    // Level BG colours: index 0 = locked (transparent), 1–4 = progressively more saturated
    private static readonly Dictionary<PerkCategory, Color[]> LevelBg = new()
    {
        [PerkCategory.Red]    = [Color.Transparent, Color.FromHex("#590000"), Color.FromHex("#8F0303"), Color.FromHex("#A50101"), Color.FromHex("#C40000")],
        [PerkCategory.Blue]   = [Color.Transparent, Color.FromHex("#000159"), Color.FromHex("#030A8F"), Color.FromHex("#0212BD"), Color.FromHex("#0426E1")],
        [PerkCategory.Green]  = [Color.Transparent, Color.FromHex("#005903"), Color.FromHex("#038F07"), Color.FromHex("#01A501"), Color.FromHex("#00C414")],
        [PerkCategory.Yellow] = [Color.Transparent, Color.FromHex("#575900"), Color.FromHex("#878F03"), Color.FromHex("#96A501"), Color.FromHex("#D7D303")],
        [PerkCategory.Purple] = [Color.Transparent, Color.FromHex("#330052"), Color.FromHex("#58028C"), Color.FromHex("#7302B8"), Color.FromHex("#9D02FC")],
    };

    private const int GridColumns = 7;
    private const int CellSize    = 64;

    public event Action<FSBuyPerkMessage>? OnBuyPerk;
    public event Action<FSEquipPerkMessage>? OnEquipPerk;
    public event Action<FSUnequipPerkMessage>? OnUnequipPerk;
    public event Action<FSSaveLoadoutMessage>? OnSaveLoadout;
    public event Action<FSLoadLoadoutMessage>? OnLoadLoadout;
    public event Action? OnRespecRequested;
    public event Action? OnPrestigeRequested;

    public PerkShopWindow()
    {
        RobustXamlLoader.Load(this);
        _res   = IoCManager.Resolve<IResourceCache>();
        _clyde = IoCManager.Resolve<IClyde>();

        // Anchor all three layers in the selected-icon stack to fill the LayoutContainer
        LayoutContainer.SetAnchorPreset(SelectedIconCatBg,   LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorPreset(SelectedIconLevelBg, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorPreset(SelectedPerkIcon, LayoutContainer.LayoutPreset.Wide);

        ShopTabs.SetTabTitle(0, "Perks");
        ShopTabs.SetTabTitle(1, "Prestige");

        FilterAll.OnPressed    += _ => SetFilter(null);
        FilterRed.OnPressed    += _ => SetFilter(PerkCategory.Red);
        FilterBlue.OnPressed   += _ => SetFilter(PerkCategory.Blue);
        FilterGreen.OnPressed  += _ => SetFilter(PerkCategory.Green);
        FilterYellow.OnPressed += _ => SetFilter(PerkCategory.Yellow);
        FilterPurple.OnPressed += _ => SetFilter(PerkCategory.Purple);
        FilterAll.Pressed = true;

        SearchBar.OnTextChanged += _ => { _search = SearchBar.Text; RebuildGrid(); };

        UpgradeButton.OnPressed += _ =>
        {
            if (_selectedId != null)
                OnBuyPerk?.Invoke(new FSBuyPerkMessage { PerkId = _selectedId });
        };

        EquipButton.OnPressed += _ =>
        {
            if (_selectedId == null || _state == null) return;
            var target = _selectedSlot;
            if (!target.HasValue || !string.IsNullOrEmpty(_state.Slots[target.Value]))
            {
                for (var i = 0; i < FSPerkDef.SlotCount; i++)
                {
                    if (string.IsNullOrEmpty(_state.Slots[i])) { target = i; break; }
                }
            }
            if (target.HasValue)
                OnEquipPerk?.Invoke(new FSEquipPerkMessage { PerkId = _selectedId, SlotIndex = target.Value });
        };

        UnequipButton.OnPressed += _ =>
        {
            if (_selectedId == null || _state == null) return;
            var slotIdx = _selectedSlot;
            if (!slotIdx.HasValue)
            {
                for (var i = 0; i < FSPerkDef.SlotCount; i++)
                    if (_state.Slots[i] == _selectedId) { slotIdx = i; break; }
            }
            if (slotIdx.HasValue)
                OnUnequipPerk?.Invoke(new FSUnequipPerkMessage { SlotIndex = slotIdx.Value });
        };

        SaveLoadout0.OnPressed += _ => OnSaveLoadout?.Invoke(new FSSaveLoadoutMessage { LoadoutIndex = 0 });
        LoadLoadout0.OnPressed += _ => OnLoadLoadout?.Invoke(new FSLoadLoadoutMessage { LoadoutIndex = 0 });
        SaveLoadout1.OnPressed += _ => OnSaveLoadout?.Invoke(new FSSaveLoadoutMessage { LoadoutIndex = 1 });
        LoadLoadout1.OnPressed += _ => OnLoadLoadout?.Invoke(new FSLoadLoadoutMessage { LoadoutIndex = 1 });
        SaveLoadout2.OnPressed += _ => OnSaveLoadout?.Invoke(new FSSaveLoadoutMessage { LoadoutIndex = 2 });
        LoadLoadout2.OnPressed += _ => OnLoadLoadout?.Invoke(new FSLoadLoadoutMessage { LoadoutIndex = 2 });

        RespecButton.OnPressed += _ => ShowRespecConfirmation();

        PrestigeButton.OnPressed += _ => ShowPrestigeConfirmation();
    }

    public void UpdateState(FSPerksStateEvent ev)
    {
        _state = ev;
        ApLabel.Text = ev.PerkPoints.ToString("N0");
        RebuildSlots();
        RebuildGrid();
        RefreshInfo();
    }

    public void UpdateLeveling(int level, int prestige)
    {
        _playerLevel = level;
        _prestigeLevel = prestige;
        RefreshPrestigeTab();
    }

    private void SetFilter(PerkCategory? cat)
    {
        _filterCategory = cat;
        FilterAll.Pressed    = cat == null;
        FilterRed.Pressed    = cat == PerkCategory.Red;
        FilterBlue.Pressed   = cat == PerkCategory.Blue;
        FilterGreen.Pressed  = cat == PerkCategory.Green;
        FilterYellow.Pressed = cat == PerkCategory.Yellow;
        FilterPurple.Pressed = cat == PerkCategory.Purple;
        RebuildGrid();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (!disposing) return;
        foreach (var tex in _iconCache.Values)
            tex.Dispose();
        _iconCache.Clear();
    }
}
