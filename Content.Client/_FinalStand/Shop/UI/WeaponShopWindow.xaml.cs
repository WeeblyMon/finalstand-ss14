using Content.Shared._FinalStand.Perks;
using Content.Shared._FinalStand.Shop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._FinalStand.Shop.UI;

[GenerateTypedNameReferences]
public sealed partial class WeaponShopWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    public event Action? OnBuyPressed;
    public event Action<string>? OnUpgradePressed;
    public event Action<string>? OnBuyPerkPressed;

    private int _price;

    public WeaponShopWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        BuyButton.OnPressed += _ => OnBuyPressed?.Invoke();
    }

    public void Populate(EntityUid shopEntity, IEntityManager entMan)
    {
        if (!entMan.TryGetComponent<FSShopWeaponComponent>(shopEntity, out var comp))
            return;

        _price = comp.Price;

        var meta = entMan.GetComponent<MetaDataComponent>(shopEntity);
        Title = "Weapon Shop";
        WeaponNameLabel.Text = Capitalize(meta.EntityName);
        WeaponNameLabel.Modulate = Color.FromHex("#F4C430");
        DescLabel.SetMessage(meta.EntityDescription);
        StatsLabel.Text = BuildStats();

        PriceLabel.Text = $"${_price:N0}";
        PriceLabel.Modulate = Color.FromHex("#EBCB8B");
        BuyButton.Text = $"Buy for ${_price:N0}";

        var shopClient = _entityManager.System<FSShopClientSystem>();
        RefreshUpgrades(comp.Upgrades, shopClient.UpgradeLevels, shopClient.CurrentCredits);
        RefreshPerks(shopEntity, entMan, shopClient.CurrentCredits);
        UpdateBalance(shopClient.CurrentCredits);
    }

    public void UpdateBalance(int credits)
    {
        BalanceLabel.Text = $"${credits:N0}";
        var canAfford = credits >= _price;
        BuyButton.Disabled = !canAfford;
        BalanceLabel.Modulate = canAfford ? Color.LimeGreen : Color.OrangeRed;
    }

    public void UpdateWeaponTitle(string title)
    {
        if (title.Length > 0)
            WeaponNameLabel.Text = Capitalize(title);
    }

    public void RefreshUpgrades(List<WeaponUpgradeDef> defs, Dictionary<string, int> levels, int credits)
    {
        UpgradesContainer.RemoveAllChildren();

        if (defs.Count == 0)
        {
            var placeholder = new Label { Text = "No upgrades available.", Modulate = Color.FromHex("#8FA1B3") };
            UpgradesContainer.AddChild(placeholder);
            return;
        }

        foreach (var def in defs)
        {
            var level = levels.GetValueOrDefault(def.Id, 0);
            UpgradesContainer.AddChild(BuildUpgradeRow(def, level, credits));
        }
    }

    public void RefreshPerks(EntityUid shopEntity, IEntityManager entMan, int credits)
    {
        PerksContainer.RemoveAllChildren();

        if (!entMan.TryGetComponent<FSShopPerksComponent>(shopEntity, out var perksComp)
            || perksComp.Perks.Count == 0)
        {
            PerksSection.Visible = false;
            return;
        }

        PerksSection.Visible = true;

        // Read the local player's active perks from the networked PerkComponent
        var localPlayer = IoCManager.Resolve<Robust.Client.Player.IPlayerManager>().LocalSession?.AttachedEntity;
        List<PerkType> activePerks = [];
        if (localPlayer != null && entMan.TryGetComponent<PerkComponent>(localPlayer.Value, out var perkComp))
            activePerks = perkComp.ActivePerks;

        foreach (var protoId in perksComp.Perks)
        {
            if (!_proto.TryIndex<PerkPrototype>(protoId, out var perkDef))
                continue;
            PerksContainer.AddChild(BuildPerkRow(perkDef, activePerks, credits));
        }
    }

    private BoxContainer BuildPerkRow(PerkPrototype perkDef, List<PerkType> activePerks, int credits)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 0, 0, 6),
        };

        var isActive = activePerks.Contains(perkDef.PerkType);
        var canAfford = credits >= perkDef.Cost;

        var btn = new Button
        {
            Text = perkDef.Name,
            MinWidth = 130,
            Disabled = perkDef.IsLocked || isActive || !canAfford,
            ToolTip = perkDef.Description,
            // TODO(finalstand): tint perk buttons distinctly once style sheet supports it
        };
        btn.Modulate = Color.FromHex("#C5E1A5"); // light green tint to distinguish from upgrade buttons
        btn.OnPressed += _ => OnBuyPerkPressed?.Invoke(perkDef.ID);
        row.AddChild(btn);

        if (perkDef.IsLocked)
        {
            btn.Disabled = true;
            var wipLabel = new Label
            {
                Text = "SOON",
                Modulate = Color.FromHex("#888888"),
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Right,
            };
            row.AddChild(wipLabel);
            return row;
        }

        var statusLabel = new Label
        {
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Right,
        };

        if (isActive)
        {
            statusLabel.Text = "ACTIVE";
            statusLabel.Modulate = Color.FromHex("#69F0AE");
        }
        else
        {
            statusLabel.Text = $"${perkDef.Cost:N0}";
            statusLabel.Modulate = canAfford ? Color.FromHex("#EBCB8B") : Color.FromHex("#BF616A");
        }

        row.AddChild(statusLabel);
        return row;
    }

    private static string Capitalize(string text)
    {
        if (text.Length == 0)
            return text;
        return text.Substring(0, 1).ToUpper() + text.Substring(1);
    }

    private BoxContainer BuildUpgradeRow(WeaponUpgradeDef def, int currentLevel, int credits)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 0, 0, 6),
        };

        var atMax = currentLevel >= def.MaxLevel;
        var nextCost = def.BaseCost * (currentLevel + 1);

        var btn = new Button
        {
            Text = def.Name,
            MinWidth = 130,
            Disabled = atMax || credits < nextCost,
            ToolTip = def.Description,
        };
        btn.OnPressed += _ => OnUpgradePressed?.Invoke(def.Id);
        row.AddChild(btn);

        if (def.IsStub)
        {
            btn.Disabled = true;
            btn.ToolTip = "Not yet implemented.";
            var wipLabel = new Label
            {
                Text = "WIP",
                Modulate = Color.FromHex("#BF616A"),
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Right,
            };
            row.AddChild(wipLabel);
            return row;
        }

        var squares = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(6, 0, 6, 0),
        };
        for (var i = 0; i < def.MaxLevel; i++)
        {
            var sq = new Label
            {
                Text = "■",
                Modulate = i < currentLevel
                    ? Color.FromHex("#A3BE8C")
                    : Color.FromHex("#434C5E"),
            };
            squares.AddChild(sq);
        }
        row.AddChild(squares);

        var costLabel = new Label
        {
            Text = atMax ? "MAX" : $"${nextCost:N0}",
            Modulate = atMax ? Color.FromHex("#A3BE8C") : Color.FromHex("#EBCB8B"),
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Right,
        };
        row.AddChild(costLabel);

        return row;
    }

    private static string BuildStats() => "—";
}
