    // The style picker lives in the title bar, left of the help and close buttons. It owns its popup so the
    // options get this window's stylesheet instead of the engine's default modal styling.
    private void BuildStyleSelector()
    {
        _styleButton.ToolTip = "Graph style";
        _styleButton.VerticalAlignment = VAlignment.Center;
        _styleButton.Margin = new Thickness(0, 0, 8, 0);
        _styleButton.MinWidth = 120;
        _styleButton.Label.FontOverride = _captionFont;
        _styleButton.OnPressed += _ => OpenStylePopup();
        UpdateStyleButton();

        if (HelpButton.Parent is not { } header)
            return;
        header.AddChild(_styleButton);
        _styleButton.SetPositionInParent(HelpButton.GetPositionInParent());
    }

    private void UpdateStyleButton()
        => _styleButton.Text = GraphControl.Style.ToString().ToUpperInvariant() + "  ▾";

    private void OpenStylePopup()
    {
        var popup = new Popup();
        ((Control) popup).Stylesheet = ((Control) this).Stylesheet;
        var panel = new PanelContainer { PanelOverride = Box(FSUiPalette.BgRecess, FSUiPalette.BorderNeutral, new Thickness(1), 2, 2) };
        var list = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 2 };
        foreach (var style in new[] { FSResearchGraphStyle.Blueprint, FSResearchGraphStyle.Schematic })
        {
            var active = style == GraphControl.Style;
            var option = new Button { Text = style.ToString().ToUpperInvariant(), MinHeight = 28, MinWidth = _styleButton.Width };
            option.Label.FontOverride = _captionFont;
            option.Label.FontColorOverride = active ? Gold : OffWhite;
            option.StyleBoxOverride = Box(active ? FSUiPalette.BgPressed : FSUiPalette.BgRecess, active ? Gold : FSUiPalette.BgRecess, new Thickness(1), 10, 0);
            option.OnPressed += _ =>
            {
                popup.Close();
                _preferredStyle = style;
                GraphControl.Style = style;
                UpdateStyleButton();
                BuildLegend();
            };
            list.AddChild(option);
        }
        panel.AddChild(list);
        popup.AddChild(panel);
        popup.OnPopupHide += popup.Orphan;

        UserInterfaceManager.ModalRoot.AddChild(popup);
        var at = _styleButton.GlobalPosition + new Vector2(0, _styleButton.Height + 2);
        popup.Open(UIBox2.FromDimensions(at, new Vector2(_styleButton.Width, 0)));
    }

    private void WireEvents()
    {
        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();
        ResetViewButton.OnPressed += _ => GraphControl.ResetView();
        ZoomInButton.OnPressed += _ => GraphControl.ZoomBy(1.2f);
        ZoomOutButton.OnPressed += _ => GraphControl.ZoomBy(1f / 1.2f);
        GraphControl.ZoomChanged += UpdateZoomLabel;
        SearchBox.OnTextChanged += args => GraphControl.SetFilter(args.Text);

        SharedTrackButton.OnPressed += _ => SelectById(ActiveResearchId());
        PickTrackButton.OnPressed += _ => SelectById(_fsResearch.MyPersonalPickId?.Id);

        PrimaryButton.OnPressed += _ =>
        {
            if (_selectedNode != null)
                OnFsNodeSelected?.Invoke(_selectedNode.Id);
        };
        QueueButton.OnPressed += _ =>
        {
            if (_selectedNode != null)
                OnFsNodeQueued?.Invoke(_selectedNode.Id);
        };
        ClearButton.OnPressed += _ =>
        {
            if (_fsResearch.IsRdOrCaptain)
                OnClearSharedPick?.Invoke();
            else
                OnClearPersonalPick?.Invoke();
        };

        GraphControl.OnNodeSelected += node =>
        {
            if (_selectedNode?.Id != node.Id)
                ClearWarning();
            _selectedNode = node;
            UpdateDetailPanel();
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        TipLabel.Visible = !IsMedicalTrack() && Width >= TipHiddenBelow;
    }

    public void SetEntity(EntityUid console)
    {
        _console = console;
        GraphControl.SetConsole(console);
        ApplyTrackStyling();
        SelectBranch(AllowedBranches().FirstOrDefault()?.ID);
        RefreshLiveState();
    }

    public void InvalidateLayout()
    {
        GraphControl.InvalidateLayout();
        RefreshLiveState();
    }

    public void RefreshLiveState()
    {
        GraphControl.SetConsole(_console);
        _selectedNode = _selectedNode != null
            ? GraphControl.GetNode(_selectedNode.Id) ?? _selectedNode
            : GraphControl.GetNode(_fsResearch.MyPersonalPickId?.Id ?? ActiveResearchId() ?? "");

        RebuildBranches();
        RebuildLines();
        UpdateStatusBar();
        UpdateDetailPanel();
    }

    public void SetContribution(int contributed, int earned)
    {
        _viewerContribution = contributed;
        _departmentEarned = earned;
        UpdateStatusBar();
    }

    public void ShowAuthorityDenied(string reason)
    {
        WarnLabel.SetMessage(Markup(reason, Rust));
        WarnLabel.Visible = true;
        _warningIsSticky = true;
    }

    private void ShowWarning(string text)
    {
        if (_warningIsSticky)
            return;
        WarnLabel.SetMessage(Markup(text, Rust));
        WarnLabel.Visible = true;
    }

    private void ClearWarning()
    {
        _warningIsSticky = false;
        WarnLabel.Visible = false;
    }

    private FSTechDatabaseComponent? Database
        => _entity.TryGetComponent<FSTechDatabaseComponent>(_console, out var db) ? db : null;

    private bool IsMedicalTrack() => Database?.Track == FSResearchTrack.Medical;

    private string? ActiveResearchId() => Database?.ActiveResearch?.Id;

    private void ApplyTrackStyling()
    {
        var medical = IsMedicalTrack();
        ServerButton.Visible = !medical;
        SharedTrackButton.Visible = !medical;
        PickTrackButton.Visible = !medical;
        PointsTitle.Text = medical ? "FUNDS" : "RP BANKED";
        PointsLabel.FontColorOverride = medical ? MedicalFundsColor : Gold;
        ResearchTitle.Text = medical ? "PURCHASE" : "RESEARCH";
    }

    private IEnumerable<FSTechBranchPrototype> AllowedBranches()
    {
        var allowed = Database?.Branches;
        return _prototype.EnumeratePrototypes<FSTechBranchPrototype>()
            .Where(b => allowed is not { Count: > 0 } || allowed.Contains(b.ID))
            .OrderBy(b => b.SortOrder);
    }

    private void SelectBranch(string? branchId)
    {
        _branch = branchId;
        GraphControl.SetBranchFilter(branchId);
        RebuildBranches();
        RebuildLines();
        UpdateGraphHeader();
    }

    // The status bar can point at a node in another branch; switch to it first.
    private void SelectById(string? id)
    {
        if (id == null || !_prototype.TryIndex<FSTechNodePrototype>(id, out var proto))
            return;

        if (_branch != null && _branch != proto.Branch.Id)
            SelectBranch(proto.Branch.Id);

        if (GraphControl.GetNode(id) is not { } node)
            return;

        _selectedNode = node;
        ClearWarning();
        UpdateDetailPanel();
    }

    private void RebuildBranches()
    {
        BranchList.RemoveAllChildren();
        var unlocked = Database?.UnlockedNodes.Select(n => n.Id).ToHashSet() ?? new HashSet<string>();
        var visible = _prototype.EnumeratePrototypes<FSTechNodePrototype>().Where(n => !n.Hidden).ToList();
        var branches = AllowedBranches().ToList();

        foreach (var branch in branches)
        {
            var inBranch = visible.Where(n => n.Branch == branch.ID).ToList();
            BranchList.AddChild(RailButton(branch.Name, $"{inBranch.Count(n => unlocked.Contains(n.ID))} / {inBranch.Count}",
                branch.Color, _branch == branch.ID, () => SelectBranch(branch.ID)));
        }

        if (branches.Count > 1)
            BranchList.AddChild(RailButton("All branches", "", null, _branch == null, () => SelectBranch(null)));
    }

    private void RebuildLines()
    {
        LineList.RemoveAllChildren();
        var lines = GraphControl.Lines.ToList();
        FSTechBranchPrototype? branch = null;
        if (_branch != null)
            _prototype.TryIndex(_branch, out branch);
        LinesTitle.Text = branch != null ? branch.Name.ToUpperInvariant() + " LINES" : "LINES";

        var accent = branch?.Color ?? Gold;
        LineList.AddChild(LineButton("All lines", $"{lines.Sum(l => l.Done)} / {lines.Sum(l => l.Total)}", accent,
            GraphControl.LineFilter == null, () => SelectLine(null)));
        foreach (var line in lines)
        {
            LineList.AddChild(LineButton("→ " + line.Name, $"{line.Done} / {line.Total}", accent,
                GraphControl.LineFilter == line.Key, () => SelectLine(line.Key)));
        }
    }

    private void SelectLine(string? key)
    {
        GraphControl.SetLineFilter(key);
        RebuildLines();
        UpdateGraphHeader();
    }

    private void UpdateGraphHeader()
    {
        var branchName = _branch != null && _prototype.TryIndex<FSTechBranchPrototype>(_branch, out var branch) ? branch.Name : "All branches";
        var lines = GraphControl.Lines.ToList();
        var line = lines.FirstOrDefault(l => l.Key == GraphControl.LineFilter);
        GraphTitle.Text = (line != null ? $"{branchName} · {line.Name}" : branchName).ToUpperInvariant();
        var done = line?.Done ?? lines.Sum(l => l.Done);
        var total = line?.Total ?? lines.Sum(l => l.Total);
        GraphCount.Text = $"{done} of {total} researched";
    }

    private void UpdateZoomLabel()
        => ZoomLabel.Text = $"{GraphControl.Zoom * 100f:0}%";

    private void UpdateStatusBar()
    {
        var db = Database;
        var points = db?.Points ?? 0;

        if (IsMedicalTrack())
        {
            PointsLabel.Text = string.Format(CultureInfo.InvariantCulture, "${0:N0}", points);
            ContributionLabel.Visible = _viewerContribution >= 0;
            ContributionLabel.Text = string.Format(CultureInfo.InvariantCulture, "You: ${0:N0} of ${1:N0}", _viewerContribution, _departmentEarned);
            return;
        }

        PointsLabel.Text = points.ToString("N0", CultureInfo.InvariantCulture);
        FillTrack(SharedTrackButton, "RD", "SHARED TARGET", "2× speed", Gold, db?.ActiveResearch?.Id, db);
        FillTrack(PickTrackButton, "YOU", "YOUR PICK", "", OffWhite, _fsResearch.MyPersonalPickId?.Id, db);
    }

    private void FillTrack(ContainerButton button, string tag, string label, string note, Color color, string? nodeId, FSTechDatabaseComponent? db)
    {
        button.RemoveAllChildren();
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4, VerticalAlignment = VAlignment.Center };

        var head = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
        head.AddChild(Chip(tag, color, FSUiPalette.BgDeep, null));
        head.AddChild(new Label { Text = label, FontOverride = _captionFont, FontColorOverride = FSUiPalette.TextMuted, VerticalAlignment = VAlignment.Center, HorizontalExpand = true });
        box.AddChild(head);

        if (nodeId == null || !_prototype.TryIndex<FSTechNodePrototype>(nodeId, out var proto))
        {
            box.AddChild(new Label { Text = "None set", FontOverride = _boldFont, FontColorOverride = Dim });
            button.Disabled = true;
            button.AddChild(box);
            return;
        }

        var progress = db?.NodeProgress.GetValueOrDefault(nodeId) ?? 0;
        var others = (db?.PersonalContributorSlots.GetValueOrDefault(nodeId)?.Count ?? 0) - (tag == "YOU" ? 1 : 0);
        if (note.Length == 0 && others > 0)
            note = $"+{others} other{(others > 1 ? "s" : "")}";
        head.AddChild(new Label { Text = note, FontColorOverride = FSUiPalette.TextMuted, VerticalAlignment = VAlignment.Center });

        box.AddChild(new Label { Text = proto.Name, FontOverride = _boldFont, FontColorOverride = OffWhite, ClipText = true, HorizontalExpand = true });
        var barRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
        barRow.AddChild(Bar(proto.Cost > 0 ? (float) progress / proto.Cost : 0f, color, 5));
        barRow.AddChild(new Label
        {
            Text = string.Format(CultureInfo.InvariantCulture, "{0:N0} / {1:N0}", progress, proto.Cost),
            FontOverride = _captionFont,
            FontColorOverride = FSUiPalette.TextMuted,
        });
        box.AddChild(barRow);

        button.Disabled = false;
        button.AddChild(box);
    }

    private void BuildLegend()
    {
        LegendRow.RemoveAllChildren();
        var items = GraphControl.Style == FSResearchGraphStyle.Schematic
            ? new[] { ("Online", Olive), ("Ready", Color.FromHex("#b9b5ae")), ("Researching", Color.FromHex("#e6c07a")), ("Offline", Color.FromHex("#3a3734")) }
            : new[] { ("Researched", Color.FromHex("#7e9464")), ("Available", Color.FromHex("#b9b5ae")), ("In progress", Gold), ("Locked", Color.FromHex("#3a3734")), ("Shop unlock", Color.FromHex("#c08a3e")) };

        foreach (var (text, color) in items)
        {
            var item = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 5 };
            item.AddChild(new PanelContainer
            {
                SetSize = new Vector2(9, 9),
                VerticalAlignment = VAlignment.Center,
                PanelOverride = Box(color.WithAlpha(0.25f), color, new Thickness(1)),
            });
            item.AddChild(new Label { Text = text, FontOverride = _captionFont, FontColorOverride = FSUiPalette.TextMuted });
            LegendRow.AddChild(item);
        }
    }

    // Corner brackets around the selected-node plate, matching the weapon shop's display plate.
    private void BuildPlateFrame()
    {
        DetailPlate.PanelOverride = Box(Color.FromHex("#0e0d0c"), FSUiPalette.BgTrack, new Thickness(1));
        var frame = new LayoutContainer { MouseFilter = MouseFilterMode.Ignore };
        foreach (var (preset, sides) in new[]
                 {
                     (LayoutContainer.LayoutPreset.TopLeft, new Thickness(2, 2, 0, 0)),
                     (LayoutContainer.LayoutPreset.TopRight, new Thickness(0, 2, 2, 0)),
                     (LayoutContainer.LayoutPreset.BottomLeft, new Thickness(2, 0, 0, 2)),
                     (LayoutContainer.LayoutPreset.BottomRight, new Thickness(0, 0, 2, 2)),
                 })
        {
            var bracket = new PanelContainer
            {
                SetSize = new Vector2(12, 12),
                PanelOverride = new StyleBoxFlat { BackgroundColor = Color.Transparent, BorderColor = Dim, BorderThickness = sides },
            };
            frame.AddChild(bracket);
            LayoutContainer.SetAnchorAndMarginPreset(bracket, preset);
        }
        DetailPlate.AddChild(frame);
    }

    private ContainerButton RailButton(string name, string count, Color? dot, bool active, Action onPressed)
    {
        var button = new ContainerButton
        {
            MinHeight = 32,
            StyleBoxOverride = Box(active ? FSUiPalette.BgElevated : Color.Transparent,
                active ? FSUiPalette.BorderNeutral : Color.Transparent, new Thickness(1), 10, 0),
        };
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 10, VerticalAlignment = VAlignment.Center };
        if (dot is { } c)
            row.AddChild(new PanelContainer { SetSize = new Vector2(8, 8), VerticalAlignment = VAlignment.Center, PanelOverride = new StyleBoxFlat { BackgroundColor = c } });
        row.AddChild(new Label { Text = name, FontOverride = _boldFont, FontColorOverride = active ? OffWhite : FSUiPalette.TextMuted, HorizontalExpand = true, ClipText = true });
        row.AddChild(new Label { Text = count, FontColorOverride = FSUiPalette.TextMuted });
        button.AddChild(row);
        button.OnPressed += _ => onPressed();
        return button;
    }

    private ContainerButton LineButton(string name, string count, Color accent, bool active, Action onPressed)
    {
        var button = new ContainerButton
        {
            MinHeight = 30,
            ToolTip = name.TrimStart('→', ' '),
            StyleBoxOverride = Box(active ? FSUiPalette.BgSurface : Color.Transparent,
                active ? accent : Color.Transparent, new Thickness(2, 0, 0, 0), 10, 4),
        };
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8, VerticalAlignment = VAlignment.Center };
        row.AddChild(new Label { Text = name, FontOverride = active ? _boldFont : _bodyFont, FontColorOverride = active ? OffWhite : FSUiPalette.TextMuted, HorizontalExpand = true, ClipText = true });
        row.AddChild(new Label { Text = count, FontColorOverride = Dim });
        button.AddChild(row);
        button.OnPressed += _ => onPressed();
        return button;
    }

    private PanelContainer Chip(string text, Color fill, Color textColor, Color? edge)
    {
        var chip = new PanelContainer
        {
            VerticalAlignment = VAlignment.Center,
            PanelOverride = Box(fill, edge ?? fill, new Thickness(1), 5, 0),
        };
        chip.AddChild(new Label { Text = text, FontOverride = _captionFont, FontColorOverride = textColor });
        return chip;
    }

    private static BoxContainer Bar(float fill, Color color, int height)
    {
        fill = Math.Clamp(fill, 0f, 1f);
        var bar = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        bar.AddChild(new PanelContainer { HorizontalExpand = true, SizeFlagsStretchRatio = Math.Max(fill, 0.0001f), SetHeight = height, PanelOverride = new StyleBoxFlat { BackgroundColor = fill > 0 ? color : FSUiPalette.BgTrack } });
        bar.AddChild(new PanelContainer { HorizontalExpand = true, SizeFlagsStretchRatio = Math.Max(1 - fill, 0.0001f), SetHeight = height, PanelOverride = new StyleBoxFlat { BackgroundColor = FSUiPalette.BgTrack } });
        return bar;
    }

    private void Caption(Label label)
    {
        label.FontOverride = _captionFont;
        label.FontColorOverride = FSUiPalette.TextMuted;
    }

    private static FormattedMessage Markup(string text, Color color)
        => FormattedMessage.FromMarkupPermissive($"[color={color.ToHex()}]{FormattedMessage.EscapeText(text)}[/color]");

    private static StyleBoxFlat Box(Color fill, Color edge, Thickness border, float padX = 0, float padY = 0)
    {
        var box = new StyleBoxFlat { BackgroundColor = fill, BorderColor = edge, BorderThickness = border };
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, padX);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, padY);
        return box;
    }
