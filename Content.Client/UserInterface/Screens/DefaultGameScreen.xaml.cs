using System.Numerics;
using Content.Client._FinalStand.Interface;
using Content.Client._FinalStand.WaveHud;
using Content.Client.UserInterface.Controls;
using Content.Client.UserInterface.Systems.Chat.Widgets;
using Content.Client.UserInterface.Systems.Actions.Widgets;
using Content.Client.UserInterface.Systems.Hotbar.Widgets;
using Content.Client.UserInterface.Systems.Inventory;
using Robust.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

using Robust.Shared.Timing;

namespace Content.Client.UserInterface.Screens;

[GenerateTypedNameReferences]
public sealed partial class DefaultGameScreen : InGameScreen
{
    private const float HandsHalfWidth = 78f;

    private const float AlertsClearance = 210f;

    // FINALSTAND: the action bar runs along the top centre. Nine slots do not fit the bottom band
    // beside the hands and the storage row, and players were paging past six far too often.
    private const float ActionBarTopMargin = 10f;

    private const int ActionColumns = ActionsBar.Columns;

    private const float BottomBandLift = 23f;

    // Only the vitals share the bottom band with the alerts now that the action bar has moved up.
    private const float AlertsLift = BottomBandLift + VitalsTallest + 6f;

    private const float VitalsTallest = 68f;

    private const float ChatEdgeMargin = 12f;

    private const float ChatDefaultWidth = 348f;
    private const float ChatDefaultHeight = 180f;
    private const float ChatMaxWidth = 520f;
    private const float ChatMaxHeight = 380f;
    private const float ChatMinWidth = 240f;
    private const float ChatMinHeight = 120f;
    private const float ChatToggleWidth = 20f;
    private const float ChatDockHeight = 34f;

    private Button? _chatDock;
    private bool _chatCollapsed;

    private UIBox2 _chatRect;
    private bool _chatPlaced;
    private bool _chatMoved;

    private Vector2 _chatScreenSize;

    private float _rightStackLift = WaveHudOverlay.RightStackMinHeight;

    private Vector2? _pendingChatSize;

    public DefaultGameScreen()
    {
        RobustXamlLoader.Load(this);

        AutoscaleMaxResolution = new Vector2i(1080, 770);

        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorPreset(ViewportContainer, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(TopLeft, LayoutPreset.TopLeft, margin: 10);
        SetAnchorAndMarginPreset(Ghost, LayoutPreset.BottomWide, margin: 80);
        SetAnchorAndMarginPreset(Hotbar, LayoutPreset.BottomWide, margin: (int) HotbarGui.BandInset);
        // FINALSTAND: chat sits above the bottom band on the right, leaving the top right to the wave panel.
        SetAnchorPreset(Chat, LayoutPreset.TopLeft);
        SetGrowHorizontal(Chat, GrowDirection.Constrain);
        SetGrowVertical(Chat, GrowDirection.Constrain);

        SetupChatToggle();

        // FINALSTAND: one question per screen region.
        SetAnchorPreset(Alerts, LayoutPreset.BottomLeft);
        SetMarginLeft(Alerts, 24f);
        SetMarginRight(Alerts, 24f);
        SetMarginTop(Alerts, -AlertsLift);
        SetMarginBottom(Alerts, -AlertsLift);
        SetGrowHorizontal(Alerts, GrowDirection.End);
        SetGrowVertical(Alerts, GrowDirection.Begin);

        SetAnchorPreset(Inventory, LayoutPreset.TopLeft);
        SetGrowHorizontal(Inventory, GrowDirection.End);
        SetGrowVertical(Inventory, GrowDirection.Begin);

        AdoptWornButton();

        Actions.ActionsContainer.MaxSize = new Vector2(9999, 9999);
        Actions.ActionsContainer.Columns = ActionColumns;
        Actions.ActionsContainer.ExpandBackwards = false;

        SetAnchorLeft(Actions, 0.5f);
        SetAnchorRight(Actions, 0.5f);
        SetAnchorTop(Actions, 0f);
        SetAnchorBottom(Actions, 0f);
        SetMarginLeft(Actions, 0f);
        SetMarginRight(Actions, 0f);
        SetMarginTop(Actions, ActionBarTopMargin);
        SetMarginBottom(Actions, ActionBarTopMargin);
        SetGrowHorizontal(Actions, GrowDirection.Both);
        SetGrowVertical(Actions, GrowDirection.End);

        Chat.OnChatResizeFinish += ChatOnResizeFinish;
        Chat.OnChatRectFinish += rect =>
        {
            _chatRect = rect;
            _chatMoved = true;
            PlaceChatDock();
        };
    }

    public void SetRightStackLift(float lift)
    {
        if (MathF.Abs(lift - _rightStackLift) < 0.5f)
            return;

        _rightStackLift = lift;

        if (!_chatMoved)
            ResetChatRect();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (Size.X > 0f && Size.Y > 0f)
        {
            if (!_chatPlaced)
                ResetChatRect();
            else if (MathF.Abs(Size.X - _chatScreenSize.X) > 0.5f
                     || MathF.Abs(Size.Y - _chatScreenSize.Y) > 0.5f)
            {
                ReflowChatForScreen();
            }
        }

        PlaceInventoryBar();
    }

    private void PlaceInventoryBar()
    {
        if (Hotbar.StoragePanel is not { } storage || storage.Size.Y <= 0f)
            return;

        var size = Inventory.DesiredSize;
        if (size.X <= 0f || size.Y <= 0f)
            return;

        var centre = storage.GlobalPosition.X + storage.Size.X * 0.5f;
        var bottom = storage.GlobalPosition.Y - InventoryBarGap;

        SetPosition(Inventory, new Vector2(centre - size.X * 0.5f, bottom - size.Y));
    }

    private const float InventoryBarGap = 6f;

    private void ReflowChatForScreen()
    {
        if (!_chatMoved)
        {
            ResetChatRect();
            return;
        }

        _chatRect = _chatRect.Translated(Size - _chatScreenSize);
        ClampChatRect();
        _chatScreenSize = Size;
        ApplyChatState();
    }

    private void ClampChatRect()
    {
        var width = MathF.Min(_chatRect.Width, Size.X);
        var height = MathF.Min(_chatRect.Height, Size.Y);
        var left = Math.Clamp(_chatRect.Left, 0f, MathF.Max(0f, Size.X - width));
        var top = Math.Clamp(_chatRect.Top, 0f, MathF.Max(0f, Size.Y - height));

        _chatRect = new UIBox2(left, top, left + width, top + height);
    }

    private void ResetChatRect()
    {
        if (Size.X <= 0f || Size.Y <= 0f)
            return;

        var right = Size.X - ChatEdgeMargin;
        var bottom = Size.Y - (BottomBandLift + _rightStackLift + 8f);
        _chatRect = new UIBox2(right - ChatDefaultWidth, bottom - ChatDefaultHeight, right, bottom);
        _chatPlaced = true;
        _chatScreenSize = Size;
        ClampChatRect();
        ApplyChatState();

        if (_pendingChatSize is { } pending)
        {
            _pendingChatSize = null;
            SetChatSize(pending);
        }
    }

    private void ChatOnResizeFinish(Vector2 size)
    {
        OnChatResized?.Invoke(new Vector2(size.Y, size.X));
    }

    public override ChatBox ChatBox => Chat;

    public override void SetChatSize(Vector2 size)
    {
        if (!_chatPlaced)
        {
            _pendingChatSize = size;
            return;
        }

        var height = Math.Clamp(MathF.Abs(size.X), ChatMinHeight, ChatMaxHeight);
        var width = Math.Clamp(MathF.Abs(size.Y), ChatMinWidth, ChatMaxWidth);
        _chatRect = new UIBox2(_chatRect.Right - width, _chatRect.Bottom - height,
            _chatRect.Right, _chatRect.Bottom);
        ApplyChatState();
    }

    private void ApplyChatState()
    {
        Chat.Visible = !_chatCollapsed;

        if (!_chatCollapsed)
            Chat.ApplyRect(_chatRect);

        PlaceChatDock();
    }

    private void PlaceChatDock()
    {
        if (_chatDock == null)
            return;

        _chatDock.Visible = _chatCollapsed;
        if (!_chatCollapsed)
            return;

        var centreY = _chatPlaced ? _chatRect.Top + _chatRect.Height * 0.5f : Size.Y * 0.5f;
        var top = Math.Clamp(centreY - ChatDockHeight * 0.5f, 0f, MathF.Max(0f, Size.Y - ChatDockHeight));

        SetMarginLeft(_chatDock, Size.X - ChatToggleWidth);
        SetMarginRight(_chatDock, Size.X);
        SetMarginTop(_chatDock, top);
        SetMarginBottom(_chatDock, top + ChatDockHeight);
    }

    // FINALSTAND: the vanilla bag toggle leads the storage row. It is the same SlotButton the
    // inventory controller already registered, so its press handler and visibility still apply -
    // only its parent changes.
    private void AdoptWornButton()
    {
        Inventory.InventoryButton.Orphan();
        Inventory.InventoryButton.SetButtonSize(WaveHudOverlay.HudSlotSize);
        Inventory.InventoryButton.ToolTip = Loc.GetString("fs-hud-worn-tooltip");

        Hotbar.FSWornSlot.AddChild(Inventory.InventoryButton);
    }

    private void SetupChatToggle()
    {
        _chatDock = new Button
        {
            Text = "◀",
            ToolTip = Loc.GetString("fs-chat-toggle-tooltip"),
            MinSize = new Vector2(ChatToggleWidth, ChatDockHeight),
            Visible = false,
        };

        FSHudStyle.StyleButton(_chatDock, padX: 2, padY: 2);

        AddChild(_chatDock);
        SetAnchorPreset(_chatDock, LayoutPreset.TopLeft);
        SetGrowHorizontal(_chatDock, GrowDirection.Constrain);
        SetGrowVertical(_chatDock, GrowDirection.Constrain);

        _chatDock.OnPressed += _ => SetChatCollapsed(false);

        Chat.FSToggle.Text = "▶";
        Chat.FSToggle.ToolTip = Loc.GetString("fs-chat-toggle-tooltip");
        Chat.FSToggle.MinSize = new Vector2(ChatToggleWidth, 16);
        FSHudStyle.StyleButton(Chat.FSToggle, padX: 2, padY: 0);
        Chat.FSToggle.OnPressed += _ => SetChatCollapsed(true);

        Chat.FSGripLabel.ModulateSelfOverride = FSPalette.TextDim;

        Chat.FSGripHint.StyleClasses.Add("LabelSubText");
        Chat.FSGripHint.ModulateSelfOverride = FSPalette.TextMuted;
    }

    private void SetChatCollapsed(bool collapsed)
    {
        if (_chatCollapsed == collapsed)
            return;

        _chatCollapsed = collapsed;
        ApplyChatState();
    }
}
