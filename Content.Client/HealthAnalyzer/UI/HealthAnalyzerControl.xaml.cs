// Health analyzer UI is split from its window because it's used by both the
// health analyzer item and the cryo pod UI.

[GenerateTypedNameReferences]
public sealed partial class HealthAnalyzerControl : BoxContainer
{
    private readonly IEntityManager _entityManager;
    private readonly SpriteSystem _spriteSystem;
    private readonly IPrototypeManager _prototypes;
    private readonly IResourceCache _cache;
    private readonly DamageableSystem _damageable;
    private readonly FSAilmentSystem _ailments;
    private readonly IGameTiming _timing;
    private readonly List<FSAilmentView> _views = new();

    public HealthAnalyzerControl()
    {
        RobustXamlLoader.Load(this);

        var dependencies = IoCManager.Instance!;
        _entityManager = dependencies.Resolve<IEntityManager>();
        _spriteSystem = _entityManager.System<SpriteSystem>();
        _prototypes = dependencies.Resolve<IPrototypeManager>();
        _cache = dependencies.Resolve<IResourceCache>();
        _damageable = _entityManager.System<DamageableSystem>();
        _ailments = _entityManager.System<FSAilmentSystem>();
        _timing = dependencies.Resolve<IGameTiming>();
    }

    public void Populate(HealthAnalyzerUiState state)
    {
        var target = _entityManager.GetEntity(state.TargetEntity);

        if (target == null
            || !_entityManager.TryGetComponent<DamageableComponent>(target, out var damageable))
        {
            NoPatientDataText.Visible = true;
            return;
        }

        NoPatientDataText.Visible = false;

        // Scan Mode

        ScanModeLabel.Text = state.ScanMode.HasValue
            ? state.ScanMode.Value
                ? Loc.GetString("health-analyzer-window-scan-mode-active")
                : Loc.GetString("health-analyzer-window-scan-mode-inactive")
            : Loc.GetString("health-analyzer-window-entity-unknown-text");

        ScanModeLabel.FontColorOverride = state.ScanMode.HasValue && state.ScanMode.Value ? Color.Green : Color.Red;

        // Patient Information

        SpriteView.SetEntity(target.Value);
        SpriteView.Visible = state.ScanMode.HasValue && state.ScanMode.Value;
        NoDataTex.Visible = !SpriteView.Visible;

        var name = new FormattedMessage();
        name.PushColor(Color.White);
        name.AddText(_entityManager.HasComponent<MetaDataComponent>(target.Value)
            ? Identity.Name(target.Value, _entityManager)
            : Loc.GetString("health-analyzer-window-entity-unknown-text"));
        NameLabel.SetMessage(name);

        SpeciesLabel.Text =
            _entityManager.TryGetComponent<HumanoidProfileComponent>(target.Value,
                out var humanoidComponent)
                ? Loc.GetString(_prototypes.Index(humanoidComponent.Species).Name)
                : Loc.GetString("health-analyzer-window-entity-unknown-species-text");

        // Basic Diagnostic

        TemperatureLabel.Text = !float.IsNaN(state.Temperature)
            ? $"{state.Temperature - Atmospherics.T0C:F1} °C ({state.Temperature:F1} K)"
            : Loc.GetString("health-analyzer-window-entity-unknown-value-text");

        StatusLabel.Text =
            _entityManager.TryGetComponent<MobStateComponent>(target.Value, out var mobStateComponent)
                ? GetStatus(mobStateComponent.CurrentState)
                : Loc.GetString("health-analyzer-window-entity-unknown-text");

        // Total Damage

        DamageLabel.Text = _damageable.GetTotalDamage(target.Value).ToString();

        PopulateAilments(target.Value, state, mobStateComponent);

        // Alerts

        var showAlerts = state.Unrevivable == true;

        AlertsDivider.Visible = showAlerts;
        AlertsContainer.Visible = showAlerts;

        if (showAlerts)
            AlertsContainer.RemoveAllChildren();

        if (state.Unrevivable == true)
            AlertsContainer.AddChild(new RichTextLabel
            {
                Text = Loc.GetString("health-analyzer-window-entity-unrevivable-text"),
                Margin = new Thickness(0, 4),
                MaxWidth = 300
            });

        // Damage Groups

        var damageSortedGroups =
            _damageable.GetDamagePerGroup(target.Value)
                .OrderByDescending(damage => damage.Value)
                .ToDictionary(x => x.Key, x => x.Value);

        var damagePerType = _damageable.GetAllDamage(target.Value).DamageDict;

        DrawDiagnosticGroups(damageSortedGroups, damagePerType);
    }

    private void PopulateAilments(EntityUid target, HealthAnalyzerUiState state, MobStateComponent? mobState)
    {
        AilmentsContainer.RemoveAllChildren();
        AilmentsContainer.Visible = _entityManager.TryGetComponent<FSAilmentStateComponent>(target, out var vitals);
        if (vitals == null)
            return;

        var now = _timing.CurTime;
        if (mobState?.CurrentState == MobState.Critical)
        {
            StatusLabel.Text = vitals.Held
                ? Loc.GetString("fs-analyzer-down-held")
                : vitals.DownEnd is { } end
                    ? Loc.GetString("fs-analyzer-down-clock", ("seconds", FSAilmentVisualsSystem.Seconds(end - now)))
                    : StatusLabel.Text;
        }
        else if (mobState?.CurrentState == MobState.Alive)
        {
            StatusLabel.Text = Loc.GetString("fs-analyzer-health", ("percent", HealthPercent(target)));
        }

        _ailments.GetViews(target, _views);
        if (_views.Count > 0)
            AddLine(Loc.GetString("fs-analyzer-ailments"));

        foreach (var view in _views)
        {
            var color = view.Ward ? FSPalette.Ok : FSAilmentVisualsSystem.SlotColor(view.Slot);
            var name = Loc.GetString(view.Name);
            if (view.Level > 0)
                name = Loc.GetString("fs-ailment-name-level", ("name", name), ("level", view.Level));

            var seconds = view.End is { } until ? FSAilmentVisualsSystem.Seconds(until - now) : 0;
            var rate = (_ailments.Rules.BleedDamage.GetTotal() * view.Level).Float();
            var effect = view.Effect is { } effectId ? Loc.GetString(effectId, ("seconds", seconds), ("rate", rate)) : string.Empty;
            var fix = view.FixHint is { } fixId ? Loc.GetString("fs-analyzer-fix", ("fix", Loc.GetString(fixId))) : string.Empty;

            AddLine(Loc.GetString("fs-analyzer-ailment-line",
                ("color", color.ToHex()), ("name", name), ("effect", effect), ("fix", fix)));
        }

        AddLine(Loc.GetString("fs-analyzer-regen", ("state", RegenState(target, vitals, mobState))));

        if (state.Reagents is not { Count: > 0 } reagents)
            return;

        var parts = new List<string>();
        foreach (var reagent in reagents)
        {
            var name = _prototypes.TryIndex<ReagentPrototype>(reagent.Reagent, out var proto) ? proto.LocalizedName : reagent.Reagent;
            name = FormattedMessage.EscapeText(name);
            parts.Add(Loc.GetString(reagent.Safe ? "fs-analyzer-reagent-safe" : "fs-analyzer-reagent-unsafe",
                ("name", name), ("amount", reagent.Quantity)));
        }

        AddLine(Loc.GetString("fs-analyzer-chemicals", ("list", string.Join(" · ", parts))));
    }

    private string RegenState(EntityUid target, FSAilmentStateComponent vitals, MobStateComponent? mobState)
    {
        var rules = _ailments.Rules;
        var percent = (int) MathF.Round(rules.RegenCap * 100f);

        if (vitals.Recovering)
            return Loc.GetString("fs-analyzer-regen-recovering");

        if (vitals.Regenerating)
            return Loc.GetString("fs-analyzer-regen-active", ("percent", percent));

        if (mobState?.CurrentState != MobState.Alive)
            return Loc.GetString("fs-analyzer-regen-down");

        if (_ailments.RegenBlocker(target) is { } blocker)
            return Loc.GetString("fs-analyzer-regen-blocked", ("ailment", Loc.GetString(blocker)));

        return Loc.GetString("fs-analyzer-regen-waiting", ("seconds", (int) rules.RegenDelay.TotalSeconds), ("percent", percent));
    }

    private int HealthPercent(EntityUid target)
    {
        var thresholds = _entityManager.System<MobThresholdSystem>();
        if (!thresholds.TryGetThresholdForState(target, MobState.Critical, out var crit) || crit is not { } critical || critical <= 0)
            return 100;

        var damage = _damageable.GetTotalDamage(target);
        return Math.Clamp((int) MathF.Round((1f - (damage / critical).Float()) * 100f), 0, 100);
    }

    private void AddLine(string markup)
    {
        var label = new RichTextLabel { MaxWidth = 300 };
        label.SetMessage(FormattedMessage.FromMarkupOrThrow(markup));
        AilmentsContainer.AddChild(label);
    }

    private static string GetStatus(MobState mobState)
    {
        return mobState switch
        {
            MobState.Alive => Loc.GetString("health-analyzer-window-entity-alive-text"),
            MobState.Critical => Loc.GetString("health-analyzer-window-entity-critical-text"),
            MobState.Dead => Loc.GetString("health-analyzer-window-entity-dead-text"),
            _ => Loc.GetString("health-analyzer-window-entity-unknown-text"),
        };
    }

    private void DrawDiagnosticGroups(
        Dictionary<ProtoId<DamageGroupPrototype>, FixedPoint2> groups,
        IReadOnlyDictionary<ProtoId<DamageTypePrototype>, FixedPoint2> damageDict)
    {
        GroupsContainer.RemoveAllChildren();

        foreach (var (damageGroupId, damageAmount) in groups)
        {
            if (damageAmount == 0)
                continue;

            var groupTitleText = $"{Loc.GetString(
                "health-analyzer-window-damage-group-text",
                ("damageGroup", _prototypes.Index<DamageGroupPrototype>(damageGroupId).LocalizedName),
                ("amount", damageAmount)
            )}";

            var groupContainer = new BoxContainer
            {
                Align = AlignMode.Begin,
                Orientation = LayoutOrientation.Vertical,
            };

            groupContainer.AddChild(CreateDiagnosticGroupTitle(groupTitleText, damageGroupId));

            GroupsContainer.AddChild(groupContainer);

            // Show the damage for each type in that group.
            var group = _prototypes.Index<DamageGroupPrototype>(damageGroupId);

            foreach (var type in group.DamageTypes)
            {
                if (!damageDict.TryGetValue(type, out var typeAmount) || typeAmount <= 0)
                    continue;

                var damageString = Loc.GetString(
                    "health-analyzer-window-damage-type-text",
                    ("damageType", _prototypes.Index<DamageTypePrototype>(type).LocalizedName),
                    ("amount", typeAmount)
                );

                groupContainer.AddChild(CreateDiagnosticItemLabel(damageString.Insert(0, " · ")));
            }
        }
    }

    private Texture GetTexture(string texture)
    {
        var rsiPath = new ResPath("/Textures/Objects/Devices/health_analyzer.rsi");
        var rsiSprite = new SpriteSpecifier.Rsi(rsiPath, texture);

        var rsi = _cache.GetResource<RSIResource>(rsiSprite.RsiPath).RSI;
        if (!rsi.TryGetState(rsiSprite.RsiState, out var state))
        {
            rsiSprite = new SpriteSpecifier.Rsi(rsiPath, "unknown");
        }

        return _spriteSystem.Frame0(rsiSprite);
    }

    private static Label CreateDiagnosticItemLabel(string text)
    {
        return new Label
        {
            Text = text,
        };
    }

    private BoxContainer CreateDiagnosticGroupTitle(string text, string id)
    {
        var rootContainer = new BoxContainer
        {
            Margin = new Thickness(0, 6, 0, 0),
            VerticalAlignment = VAlignment.Bottom,
            Orientation = LayoutOrientation.Horizontal,
        };

        rootContainer.AddChild(new TextureRect
        {
            SetSize = new Vector2(30, 30),
            Texture = GetTexture(id.ToLower())
        });

        rootContainer.AddChild(CreateDiagnosticItemLabel(text));

        return rootContainer;
    }
}
