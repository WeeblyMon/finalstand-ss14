[GenerateTypedNameReferences]
public sealed partial class FSResearchTreeMenu : FancyWindow
{
    public Action<string>? OnTechnologyCardPressed;
    public Action? OnServerButtonPressed;

    [Dependency] private readonly IEntityManager _entity = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private readonly ResearchSystem _research;

    private const int ProgressSegments = 12;

    // decorative only - a tier's dot color here is not the same signal as a node's state color
    private static readonly Color[] TierLegendColors =
    {
        FSUiPalette.TextMuted,
        FSUiPalette.StatePositive,
        Color.FromHex("#38BDF8"),
        FSUiPalette.AccentBrand,
        FSUiPalette.StatePending,
    };

    public EntityUid Entity;

    private FSResearchNodeView? _selectedNode;
    private ResearchConsoleBoundInterfaceState? _state;
    private readonly List<(Button Button, string? GroupId)> _disciplineButtons = new();

    public FSResearchTreeMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _research = _entity.System<ResearchSystem>();

        // FancyWindow shadows Control.Stylesheet with a `new string?` (registered-name lookup)
        // property, so `this.Stylesheet = ...` won't accept a Stylesheet object here the way it
        // does on WeaponShopWindow (a plain DefaultWindow) - cast to the base Control type to
        // reach the real object-typed property and actually apply the shared menu stylesheet.
        ((Control)this).Stylesheet = new FSMenuStylesheet(
            IoCManager.Resolve<IUserInterfaceManager>(), _resourceCache).Stylesheet;

        var panelBox = new StyleBoxTexture
        {
            Texture = _resourceCache.GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/panel_bg.png").Texture,
            Modulate = FSUiPalette.BgSurface,
        };
        panelBox.SetPatchMargin(StyleBox.Margin.All, FSUiPalette.PanelCornerRadius);
        GraphPanelContainer.PanelOverride = panelBox;
        DetailPanelContainer.PanelOverride = panelBox;

        StatsHeaderLabel.FontColorOverride = FSUiPalette.AccentBrand;
        RequirementsHeaderLabel.FontColorOverride = FSUiPalette.AccentBrand;

        HeaderResearchIcon.Texture = _resourceCache
            .GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/research_icon_purple.png").Texture;

        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();

        SearchBox.OnTextChanged += args => GraphControl.SetFilter(args.Text);
        GraphControl.SetScrollContainer(GraphScroll);

        BuildTierLegend();
        BuildEmptyState();

        StartResearchButton.OnPressed += _ =>
        {
            if (_selectedNode is { FsNode: null })
                OnTechnologyCardPressed?.Invoke(_selectedNode.Id);
        };

        CancelButton.OnPressed += _ =>
        {
            _selectedNode = null;
            UpdateDetailPanel();
        };

        GraphControl.OnNodeSelected += node =>
        {
            _selectedNode = node;
            UpdateDetailPanel();
        };

        UpdateDetailPanel();
    }

    public void SetEntity(EntityUid entity)
    {
        Entity = entity;
        GraphControl.SetConsole(entity);
        RebuildDisciplineRail();
    }

    // Tabs are separate pages, not a dimming filter (see FSResearchNodeGraphControl.Rebuild) - one
    // tab per FS branch (Ordnance today) shown first and selected by default, then a single
    // "VANILLA" catch-all bundling every vanilla discipline together until they get split into
    // their own pages later, then "ALL" last.
    private void RebuildDisciplineRail()
    {
        DisciplineRailContainer.RemoveAllChildren();
        _disciplineButtons.Clear();

        if (!_entity.TryGetComponent<TechnologyDatabaseComponent>(Entity, out _))
            return;

        string? defaultPage = null;
        foreach (var branch in _prototype.EnumeratePrototypes<FSTechBranchPrototype>())
        {
            AddDisciplineButton(branch.ID, branch.Name.ToUpperInvariant());
            defaultPage ??= branch.ID;
        }

        AddDisciplineButton(FSResearchNodeGraphControl.VanillaPageId, "VANILLA");
        AddDisciplineButton(null, "ALL");

        SelectDiscipline(defaultPage);
    }

    private void AddDisciplineButton(string? groupId, string label)
    {
        var button = new Button
        {
            Text = label,
            Margin = new Thickness(0, 0, 6, 0),
        };
        button.OnPressed += _ => SelectDiscipline(groupId);
        DisciplineRailContainer.AddChild(button);
        _disciplineButtons.Add((button, groupId));
    }

    private void SelectDiscipline(string? groupId)
    {
        GraphControl.SetDisciplineFilter(groupId);
        foreach (var (button, id) in _disciplineButtons)
            button.Label.FontColorOverride = id == groupId ? FSUiPalette.AccentBrand : FSUiPalette.TextMuted;
    }

    private void BuildTierLegend()
    {
        TierLegendContainer.RemoveAllChildren();

        for (var tier = 0; tier < TierLegendColors.Length; tier++)
        {
            var dot = new PanelContainer
            {
                SetWidth = 10,
                SetHeight = 10,
                Margin = new Thickness(0, 0, 4, 0),
                VerticalAlignment = VAlignment.Center,
            };
            dot.PanelOverride = new StyleBoxFlat { BackgroundColor = TierLegendColors[tier] };
            TierLegendContainer.AddChild(dot);
            TierLegendContainer.AddChild(new Label
            {
                Text = $"Tier {tier + 1}",
                Modulate = FSUiPalette.TextMuted,
                Margin = new Thickness(0, 0, 14, 0),
            });
        }

        TierLegendContainer.AddChild(new Control { HorizontalExpand = true });

        var resetButton = new Button { Text = "Reset View" };
        resetButton.OnPressed += _ => GraphControl.ResetView();
        TierLegendContainer.AddChild(resetButton);
    }

    private void BuildEmptyState()
    {
        EmptyStateContainer.RemoveAllChildren();

        var icon = new TextureRect
        {
            Texture = _resourceCache.GetResource<TextureResource>(
                "/Textures/_FinalStand/Interface/Research/research_icon_white.png").Texture,
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            SetWidth = 72,
            SetHeight = 72,
            HorizontalAlignment = HAlignment.Center,
            Modulate = FSUiPalette.TextMuted.WithAlpha(0.35f),
        };
        EmptyStateContainer.AddChild(icon);
        EmptyStateContainer.AddChild(new Label
        {
            Text = "Select a technology",
            HorizontalAlignment = HAlignment.Center,
            Modulate = FSUiPalette.TextMuted,
            Margin = new Thickness(0, 10, 0, 0),
        });
    }

    public void UpdatePanels(ResearchConsoleBoundInterfaceState state)
    {
        _state = state;
        GraphControl.SetConsole(Entity);
        UpdateDetailPanel();
    }

    public void UpdateInformationPanel(ResearchConsoleBoundInterfaceState state)
    {
        _state = state;

        var amountMsg = new FormattedMessage();
        amountMsg.AddMarkupOrThrow(Loc.GetString("research-console-menu-research-points-text",
            ("points", state.Points)));
        ResearchAmountLabel.SetMessage(amountMsg);

        UpdateDetailPanel();
    }

    private void UpdateDetailPanel()
    {
        EmptyStateContainer.Visible = _selectedNode == null;

        if (_selectedNode == null)
        {
            TechNameLabel.Text = "";
            TechDescLabel.SetMessage(new FormattedMessage());
            TechStatsLabel.SetMessage(new FormattedMessage());
            RequirementsLabel.SetMessage(new FormattedMessage());
            MaterialsLabel.Text = "Materials Needed: —";
            RpNeededLabel.Text = "RP Needed: —";
            BuildProgressBar(0f);
            StartResearchButton.Disabled = true;
            StartResearchButton.Text = "Start Research";
            return;
        }

        var node = _selectedNode;
        TechNameLabel.Text = node.Name;

        if (node.Vanilla is { } tech)
            UpdateDetailPanelVanilla(tech);
        else if (node.FsNode is { } fsNode)
            UpdateDetailPanelFsNode(fsNode);

        RequirementsLabel.SetMessage(BuildRequirementsMessage(node));

        MaterialsLabel.Text = "Materials Needed: —";
        RpNeededLabel.Text = $"RP Needed: {node.Cost}";

        if (node.FsNode != null)
        {
            // Stage-3 territory: the RP-progress-bar research flow (select a node, incoming RP
            // feeds its progress) isn't wired yet, so FS nodes show an honest zero fill and a
            // disabled button rather than comparing against vanilla's unrelated point pool.
            BuildProgressBar(0f);
            StartResearchButton.Text = "Start Research";
            StartResearchButton.Disabled = true;
            return;
        }

        var points = _state?.Points ?? 0;
        var fill = node.Cost > 0 ? Math.Min(1f, (float)points / node.Cost) : 1f;
        BuildProgressBar(fill);

        StartResearchButton.Text = node.State == FSResearchNodeState.Unlocked ? "Researched" : "Start Research";
        StartResearchButton.Disabled = node.State != FSResearchNodeState.Available || points < node.Cost;
    }

    private void UpdateDetailPanelVanilla(TechnologyPrototype tech)
    {
        // GetTechnologyDescription indexes RecipeUnlocks with a throwing Index() call; some techs
        // reference lathe recipes that don't exist in this build's prototype set, which would
        // otherwise crash the whole panel (and leave the graph's click/drag state stuck).
        try
        {
            TechDescLabel.SetMessage(_research.GetTechnologyDescription(tech, includeCost: false, includeTier: false));
        }
        catch (UnknownPrototypeException)
        {
            TechDescLabel.SetMessage(new FormattedMessage());
        }

        // RecipeUnlocks is already listed under "Unlocks:" by GetTechnologyDescription above -
        // repeating "<name> Unlocked" for every recipe here was pure duplication when a tech's
        // only effect is unlocking machines/recipes. Only show something here when there's an
        // actual buff/stat description (GenericUnlocks), otherwise it's just a dash.
        var statLines = new List<string>();
        foreach (var generic in tech.GenericUnlocks)
        {
            if (!string.IsNullOrEmpty(generic.UnlockDescription))
                statLines.Add(Loc.GetString(generic.UnlockDescription));
        }
        var statsMsg = new FormattedMessage();
        statsMsg.AddText(statLines.Count > 0 ? string.Join("\n", statLines) : "—");
        TechStatsLabel.SetMessage(statsMsg);
    }

    private void UpdateDetailPanelFsNode(FSTechNodePrototype fsNode)
    {
        var descMsg = new FormattedMessage();
        if (fsNode.WeaponShopUnlock is { } shopId)
        {
            var shopName = _prototype.TryIndex<EntityPrototype>(shopId, out var shopProto) ? shopProto.Name : shopId.Id;
            descMsg.AddText($"Unlocks purchase access to the {shopName} shop table.");
        }
        if (fsNode.ExclusiveGroup != null)
        {
            if (fsNode.WeaponShopUnlock != null)
                descMsg.PushNewline();
            descMsg.AddText("Mutually exclusive choice - researching this locks out its alternative(s).");
        }
        TechDescLabel.SetMessage(descMsg);

        var statsMsg = new FormattedMessage();
        statsMsg.AddText(fsNode.BonusDescription != string.Empty ? Loc.GetString(fsNode.BonusDescription) : "—");
        TechStatsLabel.SetMessage(statsMsg);
    }

    // Prerequisite ids can point at either an FSTechNodePrototype or a vanilla TechnologyPrototype
    // (cross-branch joins, e.g. Tesla Cannon requiring the Experimental AnomalyCoreHarnessing) -
    // resolve names/unlocked-state across both prototype pools. PrerequisiteGroups (AND-of-OR,
    // e.g. a capstone needing "at least one choice per branch") render as "A OR B" lines, colored
    // by whether any one entry in the group is unlocked rather than all of them.
    private FormattedMessage BuildRequirementsMessage(FSResearchNodeView node)
    {
        var lines = new List<string>();

        foreach (var prereqId in node.Prerequisites)
        {
            var reqColor = IsIdUnlocked(prereqId) ? FSUiPalette.StatePositive : FSUiPalette.StateNegative;
            lines.Add($"[color={reqColor.ToHex()}]{ResolveNodeName(prereqId)}[/color]");
        }

        foreach (var group in node.PrerequisiteGroups)
        {
            var reqColor = group.Any(IsIdUnlocked) ? FSUiPalette.StatePositive : FSUiPalette.StateNegative;
            var names = string.Join(" OR ", group.Select(ResolveNodeName));
            lines.Add($"[color={reqColor.ToHex()}]{names}[/color]");
        }

        var msg = new FormattedMessage();
        if (lines.Count == 0)
        {
            msg.AddText("—");
            return msg;
        }

        for (var i = 0; i < lines.Count; i++)
        {
            msg.AddMarkupOrThrow(lines[i]);
            if (i < lines.Count - 1)
                msg.PushNewline();
        }

        return msg;
    }

    private bool IsIdUnlocked(string id)
    {
        if (_entity.TryGetComponent<TechnologyDatabaseComponent>(Entity, out var db) && db.UnlockedTechnologies.Any(u => u.Id == id))
            return true;
        if (_entity.TryGetComponent<FSTechDatabaseComponent>(Entity, out var fsDb) && fsDb.UnlockedNodes.Any(u => u.Id == id))
            return true;
        return false;
    }

    private string ResolveNodeName(string id)
    {
        if (_prototype.TryIndex<FSTechNodePrototype>(id, out var fsProto))
            return Loc.GetString(fsProto.Name);
        if (_prototype.TryIndex<TechnologyPrototype>(id, out var techProto))
            return Loc.GetString(techProto.Name);
        return id;
    }

    private void BuildProgressBar(float fill)
    {
        ProgressBarContainer.RemoveAllChildren();
        var filled = (int)Math.Round(Math.Clamp(fill, 0f, 1f) * ProgressSegments);
        for (var i = 0; i < ProgressSegments; i++)
        {
            var seg = new PanelContainer
            {
                HorizontalExpand = true,
                SetHeight = 10,
                Margin = new Thickness(i == 0 ? 0 : 1, 0, 0, 0),
            };
            seg.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = i < filled ? FSUiPalette.StatePositive : FSUiPalette.BgRecess,
            };
            ProgressBarContainer.AddChild(seg);
        }
    }
}
