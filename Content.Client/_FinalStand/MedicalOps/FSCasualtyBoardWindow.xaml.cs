using System.Numerics;
using Content.Client._FinalStand.Ailments;
using Content.Client._FinalStand.Interface;
using Content.Shared._FinalStand.MedicalOps;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._FinalStand.MedicalOps;

public readonly record struct FSCasualtyRow(FSCasualtyEntry Entry, float? Distance, Vector2? Direction, string State, string Needs);

[GenerateTypedNameReferences]
public sealed partial class FSCasualtyBoardWindow : DefaultWindow
{

    [Dependency] private IEntityManager _entityManager = default!;

    public event Action<NetEntity>? OnRespond;
    public event Action<NetEntity>? OnTag;

    private readonly Dictionary<NetEntity, Bearing> _bearings = new();

    public FSCasualtyBoardWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Populate(List<FSCasualtyRow> rows, bool canTag)
    {
        Entries.DisposeAllChildren();
        _bearings.Clear();
        EmptyLabel.Visible = rows.Count == 0;

        foreach (var row in rows)
        {
            var entry = row.Entry;
            var line = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 2),
            };

            if (entry.Priority)
            {
                line.AddChild(new Label
                {
                    Text = Loc.GetString("fs-casualty-priority"),
                    Modulate = FSPalette.Money,
                    Margin = new Thickness(0, 0, 4, 0),
                    VerticalAlignment = VAlignment.Center,
                });
            }

            line.AddChild(new Label
            {
                Text = row.State,
                Modulate = FSCasualtyBoardSystem.StateColor(entry),
                MinWidth = 96,
                VerticalAlignment = VAlignment.Center,
            });

            line.AddChild(new Label
            {
                Text = entry.Name,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            });

            var visuals = _entityManager.System<FSAilmentVisualsSystem>();
            foreach (var slot in FSAilmentVisualsSystem.Slots)
            {
                if (!FSAilmentVisualsSystem.Has(entry.Pips, slot) || visuals.Pip(slot) is not { } pip)
                    continue;

                line.AddChild(new TextureRect
                {
                    Texture = pip,
                    TextureScale = new Vector2(2f, 2f),
                    Modulate = FSAilmentVisualsSystem.SlotColor(slot),
                    VerticalAlignment = VAlignment.Center,
                    Margin = new Thickness(1, 0),
                });
            }

            if (row.Needs.Length > 0)
            {
                line.AddChild(new Label
                {
                    Text = row.Needs,
                    Modulate = FSPalette.Money,
                    Margin = new Thickness(4, 0),
                    VerticalAlignment = VAlignment.Center,
                });
            }

            var arrow = new FSBearingArrow
            {
                MinWidth = 18,
                MinHeight = 18,
                ArrowColor = FSCasualtyBoardSystem.StateColor(entry),
                Direction = row.Direction,
                VerticalAlignment = VAlignment.Center,
            };
            line.AddChild(arrow);

            var distance = new Label
            {
                Text = DistanceText(row.Distance),
                Modulate = FSPalette.TextMuted,
                MinWidth = 46,
                VerticalAlignment = VAlignment.Center,
            };
            line.AddChild(distance);

            _bearings[entry.Patient] = new Bearing(arrow, distance);

            if (entry.Responder is { } responder)
            {
                line.AddChild(new Label
                {
                    Text = Loc.GetString("fs-casualty-board-en-route", ("medic", responder)),
                    Modulate = FSPalette.TextMuted,
                    VerticalAlignment = VAlignment.Center,
                });
            }
            else
            {
                var patient = entry.Patient;
                var button = new Button
                {
                    Text = Loc.GetString("fs-casualty-board-respond"),
                    MinWidth = 90,
                };
                button.OnPressed += _ => OnRespond?.Invoke(patient);
                line.AddChild(button);
            }

            if (canTag)
            {
                var tagged = entry.Patient;
                var tag = new Button
                {
                    Text = Loc.GetString(entry.Priority ? "fs-casualty-board-untag" : "fs-casualty-board-tag"),
                    MinWidth = 70,
                };
                tag.OnPressed += _ => OnTag?.Invoke(tagged);
                line.AddChild(tag);
            }

            Entries.AddChild(line);
        }
    }

    public void UpdateBearing(NetEntity patient, float? distance, Vector2? direction)
    {
        if (!_bearings.TryGetValue(patient, out var bearing))
            return;

        bearing.Arrow.Direction = direction;
        bearing.Distance.Text = DistanceText(distance);
    }

    private static string DistanceText(float? distance)
    {
        return distance is { } value ? $"{value:0}m" : string.Empty;
    }

    private readonly record struct Bearing(FSBearingArrow Arrow, Label Distance);
}
