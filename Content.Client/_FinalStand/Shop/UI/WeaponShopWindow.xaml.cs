    public WeaponShopWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        Stylesheet = new FSMenuStylesheet(IoCManager.Resolve<IUserInterfaceManager>(), IoCManager.Resolve<IResourceCache>()).Stylesheet;

        foreach (var child in UpgradesScroll.Children)
        {
            if (child is ScrollBar bar)
            {
                bar.SetWidth = 5;
                bar.Modulate = new Color(0.6f, 0.6f, 0.6f, 0.35f);
            }
        }

        BuyButton.OnPressed += _ =>
        {
            _flashBuyRemaining = 0.3f;
            OnBuyPressed?.Invoke();
        };

        SellButton.OnPressed += _ =>
        {
            if (_inConfirmState)
            {
                OnSellConfirmed?.Invoke();
                ExitConfirmState();
            }
            else
            {
                EnterConfirmState();
            }
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_flashBuyRemaining > 0f)
        {
            _flashBuyRemaining = Math.Max(0f, _flashBuyRemaining - args.DeltaSeconds);
            var t = _flashBuyRemaining / 0.3f;
            var v = 0.55f + 0.45f * (1f - t);
            BuyButton.Modulate = new Color(v, 1f, v);
        }

        if (_confirmTimer > 0f)
        {
            _confirmTimer -= args.DeltaSeconds;
            if (_confirmTimer <= 0f)
                ExitConfirmState();
        }
    }

    public void UpdateSellButton(int refund, bool hasWeapon)
    {
        _sellRefund = refund;
        SellButton.Disabled = !hasWeapon;
        if (!_inConfirmState)
        {
            SellButton.Text = $"Sell  ${refund:N0}";
            SellButton.Modulate = Color.White;
        }
    }

    public void ResetConfirmation()
    {
        if (_inConfirmState)
            ExitConfirmState();
    }

    private void EnterConfirmState()
    {
        _inConfirmState = true;
        _confirmTimer = ConfirmTimeout;
        SellButton.Text = "Confirm?";
        SellButton.Modulate = FSUiPalette.StateNegative;
        SellConfirmLabel.Text = "This cannot be undone.";
        SellConfirmLabel.Visible = true;
        SellConfirmLabel.Modulate = FSUiPalette.StatePending;
    }

    private void ExitConfirmState()
    {
        _inConfirmState = false;
        _confirmTimer = 0f;
        SellConfirmLabel.Visible = false;
        SellButton.Text = $"Sell  ${_sellRefund:N0}";
        SellButton.Modulate = Color.White;
    }

    public void Populate(EntityUid shopEntity, IEntityManager entMan)
    {
        if (!entMan.TryGetComponent<FSShopWeaponComponent>(shopEntity, out var comp))
            return;

        _price = comp.Price;
        _weaponProtoId = comp.WeaponProtoId;
        _isGrenadePackShop = _weaponProtoId is { } pid
            && _proto.TryIndex<EntityPrototype>(pid, out var wEntProto)
            && wEntProto.TryGetComponent<FSGrenadePackComponent>(out _, _entityManager.ComponentFactory);

        Title = "Weapon Shop";
        WeaponNameLabel.Text = Capitalize(entMan.GetComponent<MetaDataComponent>(shopEntity).EntityName);
        WeaponNameLabel.Modulate = Color.FromHex("#F4C430");
        CategoryLabel.Text = comp.Category;
        CategoryLabel.Modulate = FSUiPalette.TextMuted;
        DescLabel.SetMessage(entMan.GetComponent<MetaDataComponent>(shopEntity).EntityDescription);

        BuyButton.Text = $"Buy  ${_price:N0}";

        var shopClient = _entityManager.System<FSShopClientSystem>();
        BuildStatBars(comp, shopClient.FindOwnedWeapon(comp.WeaponProtoId), entMan);
        RefreshUpgrades(comp.Upgrades, shopClient.UpgradeLevels, shopClient.CurrentCredits);
        UpdateBalance(shopClient.CurrentCredits);
    }

    public void UpdateBalance(int credits)
    {
        BalanceLabel.Text = $"${credits:N0}";
        BalanceLabel.Modulate = credits >= _price ? FSUiPalette.StatePositive : FSUiPalette.StateNegative;

        if (_isGrenadePackShop)
        {
            var shopClient = _entityManager.System<FSShopClientSystem>();
            if (shopClient.PlayerHasWeaponInInventory(shopClient.GetLocalPlayer(), _weaponProtoId))
            {
                BuyButton.Disabled = true;
                BuyButton.Text = "OWNED";
                BuyButton.Modulate = new Color(0.5f, 0.5f, 0.5f);
                return;
            }
            BuyButton.Text = $"Buy  ${_price:N0}";
            BuyButton.Modulate = Color.White;
        }

        BuyButton.Disabled = credits < _price;
    }

    public void UpdateWeaponTitle(string title)
    {
        if (title.Length > 0)
            WeaponNameLabel.Text = Capitalize(title);
    }

    public void RefreshStatBars(FSShopWeaponComponent comp, EntityUid? gun, IEntityManager entMan)
