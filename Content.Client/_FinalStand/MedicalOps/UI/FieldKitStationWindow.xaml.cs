        ContextPanel.PanelOverride = Box(Color.FromHex("#0e0d0c"), FSUiPalette.BgTrack, new Thickness(1));

        foreach (var caption in new[] { SatchelTitle, TankTitle, BatchTitle, AmountTitle, FromJugTitle, LabelTitle, JugTitle, ContextTitle })
            Caption(caption);
        TankTitle.FontColorOverride = OliveText;
        SatchelLabel.FontOverride = _big;
        SatchelLabel.FontColorOverride = Color.FromHex("#b9c48f");
        SatchelHint.FontColorOverride = Dim;
        TankLabel.FontOverride = _bold;
        TankHint.FontColorOverride = Dim;
        JugLabel.FontColorOverride = FSUiPalette.TextMuted;
        PackJugLabel.FontOverride = _bold;

        DumpButton.Label.FontOverride = _bold;
        DumpButton.Label.HorizontalAlignment = HAlignment.Center;
        DumpButton.OnPressed += _ => OnDump?.Invoke();
        foreach (var button in new[] { EmptyButton, EjectButton })
        {
