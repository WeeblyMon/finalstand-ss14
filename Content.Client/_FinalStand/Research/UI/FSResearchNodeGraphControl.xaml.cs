namespace Content.Client._FinalStand.Research.UI;

// HOI4-national-focus-style layout: tier flows top-down (row = tier), siblings spread
// horizontally, parent->child edges are orthogonal "elbow" connectors, and each node is an
// icon tile with a name plate underneath instead of a circle. Column position within a row is
// chosen by a single-pass barycenter of each node's prerequisite X positions (already-placed
// parent tiers), falling back to discipline grouping for roots — enough to keep branches visually
// coherent without a full graph-layout solver. Mouse wheel zooms (intercepted here so the parent
// ScrollContainer doesn't also scroll on the same gesture).
[GenerateTypedNameReferences]
public sealed partial class FSResearchNodeGraphControl : BoxContainer
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private readonly ResearchSystem _research;
    private readonly SpriteSystem _sprite;
    private readonly FontResource _fontResource;
    private readonly Texture _discTexture;
    private readonly Texture _ringTexture;
    private readonly Texture _glowTexture;
    private readonly Texture _plateBgTexture;
    private readonly Texture _plateRingTexture;
    private readonly Texture _blueprintTexture;
    private Font _font;

    private EntityUid? _console;
    private TechnologyPrototype? _hoveredTech;
    private string _filter = "";
    private ProtoId<TechDisciplinePrototype>? _disciplineFilter;
    private float _zoom = 1f;

    private ScrollContainer? _scrollContainer;
    private bool _leftDown;
    private bool _dragging;
    private Vector2 _dragStartCursor;
    private float _dragStartVScroll;
    private float _dragStartHScroll;
    private const float DragThreshold = 4f;

    private List<TechnologyPrototype> _techs = new();
    private Dictionary<string, Vector2> _positions = new();

    public event Action<TechnologyPrototype>? OnNodeSelected;

    private const float MinZoom = 0.5f;
    private const float MaxZoom = 2f;
    private const float BaseFontSize = 16f;
    private const int PlateMaxChars = 20;

    private float IconSize => 96 * UIScale * _zoom;
    private float IconBorderThickness => 6 * UIScale * _zoom;
    // wide enough for PlateMaxChars at this font before the plate itself has to grow past it
    private float PlateWidth => 300 * UIScale * _zoom;
    private float MinPlateWidth => IconSize;
    // Single line only (see TruncateForPlate) - a plate sized for 2 lines but showing 1 looked
    // tall and unbalanced, which was the actual "boxes look uneven" complaint, not a padding
    // issue. Sized from the font's real metrics, not a guessed constant, so it always exactly
    // fits one line + real breathing room (not just enough to avoid clipping).
    private float PlateHeight => _font.GetLineHeight(1) + 17 * UIScale * _zoom;
    private float PlateGap => 7 * UIScale * _zoom;
    private float NodeHeight => IconSize + PlateGap + PlateHeight;
    private float ColumnSpacing => PlateWidth + 48 * UIScale * _zoom;
    private float RowSpacing => NodeHeight + 92 * UIScale * _zoom;
    private float Padding => ColumnSpacing / 2f;

    public Color LockedNodeColor { get; set; } = FSUiPalette.BorderNeutral;
    public Color AvailableNodeColor { get; set; } = FSUiPalette.TextPrimary;
    public Color UnlockedNodeColor { get; set; } = FSUiPalette.StatePending;
    public Color HoverGlowColor { get; set; } = FSUiPalette.TextPrimary;
    public Color PlateBackgroundColor { get; set; } = FSUiPalette.BgSurface;

    public FSResearchNodeGraphControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _research = _entityManager.System<ResearchSystem>();
        _sprite = _entityManager.System<SpriteSystem>();

        _fontResource = _resourceCache.GetResource<FontResource>("/EngineFonts/NotoSans/NotoSansMono-Regular.ttf");
        _font = new VectorFont(_fontResource, (int)Math.Round(BaseFontSize));

        _discTexture = _resourceCache.GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/node_disc.png").Texture;
        _ringTexture = _resourceCache.GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/node_ring.png").Texture;
        _glowTexture = _resourceCache.GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/node_glow.png").Texture;
        _plateBgTexture = _resourceCache.GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/plate_bg.png").Texture;
        _plateRingTexture = _resourceCache.GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/plate_ring.png").Texture;
        _blueprintTexture = _resourceCache.GetResource<TextureResource>("/Textures/_FinalStand/Interface/Research/blueprint_bg.png").Texture;
    }

    public void SetConsole(EntityUid? console)
    {
        _console = console;
        Rebuild();
    }

    public void SetFilter(string filter)
    {
        _filter = filter.Trim();
    }

    public void SetDisciplineFilter(ProtoId<TechDisciplinePrototype>? discipline)
    {
        _disciplineFilter = discipline;
    }

    public void SetScrollContainer(ScrollContainer scrollContainer)
    {
        _scrollContainer = scrollContainer;
    }

    public void ResetView()
    {
        _zoom = 1f;
        Rebuild();
        if (_scrollContainer == null)
            return;
        _scrollContainer.HScroll = 0f;
        _scrollContainer.VScroll = 0f;
    }

    private void Rebuild()
    {
        _font = new VectorFont(_fontResource, Math.Clamp((int)Math.Round(BaseFontSize * _zoom), 8, 30));

        _techs = new List<TechnologyPrototype>();
        _positions = new Dictionary<string, Vector2>();

        if (_console is not { } console ||
            !_entityManager.TryGetComponent<TechnologyDatabaseComponent>(console, out var database))
        {
            MinWidth = 0;
            MinHeight = 0;
            return;
        }

        var rows = database.SupportedDisciplines;
        var techs = _prototype.EnumeratePrototypes<TechnologyPrototype>()
            .Where(t => !t.Hidden && rows.Contains(t.Discipline))
            .ToList();
        if (rows.Count == 0 || techs.Count == 0)
        {
            MinWidth = 0;
            MinHeight = 0;
            return;
        }

        _techs = techs;

        // "strays" - techs with no edge at all (not a prerequisite for anything, and have none
        // themselves) - get grouped in their own block to the right instead of scattered inline
        var techIds = techs.Select(t => t.ID).ToHashSet();
        var edgeTechIds = new HashSet<string>();
        foreach (var tech in techs)
        {
            foreach (var prereqId in tech.TechnologyPrerequisites)
            {
                if (!techIds.Contains(prereqId.Id))
                    continue;
                edgeTechIds.Add(tech.ID);
                edgeTechIds.Add(prereqId.Id);
            }
        }

        var connected = techs.Where(t => edgeTechIds.Contains(t.ID)).ToList();
        var strays = techs.Where(t => !edgeTechIds.Contains(t.ID))
            .OrderBy(t => rows.IndexOf(t.Discipline))
            .ThenBy(t => t.ID, StringComparer.Ordinal)
            .ToList();

        var xByTech = new Dictionary<string, float>();
        var yByTier = new Dictionary<int, float>();
        var maxSlots = 1;
        var rowIndex = 0;

        var tierGroups = connected.GroupBy(t => t.Tier).OrderBy(g => g.Key);
        foreach (var tierGroup in tierGroups)
        {
            var ordered = tierGroup
                .OrderBy(t => GetBarycenterX(t, xByTech, rows))
                .ThenBy(t => rows.IndexOf(t.Discipline))
                .ThenBy(t => t.ID, StringComparer.Ordinal)
                .ToList();

            for (var i = 0; i < ordered.Count; i++)
                xByTech[ordered[i].ID] = Padding + i * ColumnSpacing;

            maxSlots = Math.Max(maxSlots, ordered.Count);
            yByTier[tierGroup.Key] = Padding + rowIndex * RowSpacing;
            rowIndex++;
        }

        foreach (var tech in connected)
            _positions[tech.ID] = new Vector2(xByTech[tech.ID], yByTier[tech.Tier]);

        var strayRowCount = Math.Max(rowIndex, 1);
        var strayMaxCol = maxSlots - 1;
        for (var i = 0; i < strays.Count; i++)
        {
            var col = maxSlots + i / strayRowCount;
            var row = i % strayRowCount;
            strayMaxCol = Math.Max(strayMaxCol, col);
            _positions[strays[i].ID] = new Vector2(Padding + col * ColumnSpacing, Padding + row * RowSpacing);
        }

        MinWidth = (Padding * 2 + strayMaxCol * ColumnSpacing + PlateWidth) / UIScale;
        MinHeight = (Padding * 2 + (rowIndex - 1) * RowSpacing + NodeHeight) / UIScale;
    }

    private static float GetBarycenterX(TechnologyPrototype tech, Dictionary<string, float> placedX,
        List<ProtoId<TechDisciplinePrototype>> rows)
    {
        var parentXs = tech.TechnologyPrerequisites
            .Where(p => placedX.ContainsKey(p.Id))
            .Select(p => placedX[p.Id])
            .ToList();
        if (parentXs.Count > 0)
            return parentXs.Average();

        // no placed parent (root, or prerequisite outside this discipline set) - keep
        // same-discipline roots clustered together instead of all colliding at x=0
        return rows.IndexOf(tech.Discipline) * 100000f;
    }

    private Vector2 CurrentCursor()
        => (UserInterfaceManager.MousePositionScaled.Position * UIScale) - GlobalPixelPosition;

    // Logical screen-space position, independent of this control's own position. Dragging must use
    // this (not CurrentCursor) - scrolling moves this control, which would move GlobalPixelPosition
    // mid-drag and feed back into the delta calculation, causing the jitter/shake bug. Left unscaled
    // (no *UIScale) since ScrollContainer's HScroll/VScroll are logical units, same as this.
    private Vector2 ScreenCursor()
        => UserInterfaceManager.MousePositionScaled.Position;

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Handled || args.Function != EngineKeyFunctions.UIClick)
            return;

        _leftDown = true;
        _dragging = false;
        _dragStartCursor = ScreenCursor();
        _dragStartVScroll = _scrollContainer?.VScroll ?? 0f;
        _dragStartHScroll = _scrollContainer?.HScroll ?? 0f;
    }

    protected override void KeyBindUp(GUIBoundKeyEventArgs args)
    {
        base.KeyBindUp(args);

        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        // _leftDown/_dragging must always clear even if a subscriber throws (e.g. a selected
        // tech with bad recipe data crashing the description lookup) - otherwise the drag state
        // gets stuck and every click after looks like a drag until one more click clears it.
        try
        {
            if (!_dragging && _hoveredTech != null)
            {
                OnNodeSelected?.Invoke(_hoveredTech);
                UserInterfaceManager.ClickSound();
            }
        }
        finally
        {
            _leftDown = false;
            _dragging = false;
        }
    }

    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (!_leftDown || _scrollContainer == null)
            return;

        var cursor = ScreenCursor();
        var delta = cursor - _dragStartCursor;
        if (!_dragging && delta.LengthSquared() < DragThreshold * DragThreshold)
            return;

        _dragging = true;
        _scrollContainer.HScroll = _dragStartHScroll - delta.X;
        _scrollContainer.VScroll = _dragStartVScroll - delta.Y;
    }

    protected override void MouseWheel(GUIMouseWheelEventArgs args)
    {
        base.MouseWheel(args);

        var newZoom = Math.Clamp(_zoom + args.Delta.Y * 0.1f, MinZoom, MaxZoom);
        if (Math.Abs(newZoom - _zoom) > 0.0001f)
        {
            _zoom = newZoom;
            Rebuild();
        }

        args.Handle();
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        _hoveredTech = null;
        if (_console is not { } console ||
            !_entityManager.TryGetComponent<TechnologyDatabaseComponent>(console, out var database) ||
            _techs.Count == 0)
            return;

        var origin = Position;
        var cursor = CurrentCursor();

        DrawBlueprintBackground(handle, origin);

        // anchors dip a few px INTO the icon ring / plate box (rather than stopping exactly
        // flush with the edge) so the connector always visibly touches the node - the node
        // itself is drawn on top and covers the overlap, no gap no matter the rounding
        var edgeOverlap = 6 * UIScale * _zoom;

        Vector2 GetCenter(TechnologyPrototype tech) => origin + _positions[tech.ID];
        Vector2 GetTopAnchor(TechnologyPrototype tech) => GetCenter(tech) - new Vector2(0, IconSize / 2 - edgeOverlap);
        Vector2 GetBottomAnchor(TechnologyPrototype tech) => GetCenter(tech) + new Vector2(0, IconSize / 2 + PlateGap + PlateHeight - edgeOverlap);

        // Connectors are grouped by parent so a multi-child fan-out shares one trunk (a single
        // drop from the parent, one horizontal bus, then a short stub into each child) instead
        // of every edge drawing its own independent elbow. Independent per-edge routing put
        // multiple horizontal segments at the same midY when siblings share a row, which could
        // visually pass through/along an unrelated node and read as a connection that isn't real.
        var childrenByParent = new Dictionary<string, List<TechnologyPrototype>>();
        foreach (var tech in _techs)
        {
            foreach (var prereqId in tech.TechnologyPrerequisites)
            {
                var prereq = _techs.FirstOrDefault(t => t.ID == prereqId.Id);
                if (prereq == null)
                    continue;

                if (!childrenByParent.TryGetValue(prereq.ID, out var list))
                    childrenByParent[prereq.ID] = list = new List<TechnologyPrototype>();
                list.Add(tech);
            }
        }

        Color EdgeStateColor(TechnologyPrototype tech) => database.UnlockedTechnologies.Any(u => u.Id == tech.ID)
            ? UnlockedNodeColor
            : LockedNodeColor;

        foreach (var (parentId, allChildren) in childrenByParent)
        {
            var parent = _techs.First(t => t.ID == parentId);
            var parentCenter = GetCenter(parent);
            var parentBottom = GetBottomAnchor(parent);
            var trunkColor = EdgeStateColor(parent);

            // Tech tier doesn't strictly guarantee a prerequisite sits in a strictly-lower row
            // (two techs can share a tier while one still requires the other) - a normal
            // drop-then-bus elbow assumes the child is below the parent, and for a same-row
            // (or "above") child that puts the horizontal segment mid-row, cutting right through
            // the icons and reading as a wrong/crossed connection. Route those laterally instead:
            // a straight line between the two icons' facing edges at icon-center height.
            var children = new List<TechnologyPrototype>();
            foreach (var child in allChildren)
            {
                var childCenter = GetCenter(child);
                if (childCenter.Y > parentCenter.Y + 1f)
                {
                    children.Add(child);
                    continue;
                }

                var iconR = IconSize / 2;
                var dir = childCenter.X >= parentCenter.X ? 1f : -1f;
                var from = parentCenter + new Vector2(dir * iconR, 0);
                var to = childCenter - new Vector2(dir * iconR, 0);
                handle.DrawLine(from, to, EdgeStateColor(child));
            }

            if (children.Count == 0)
                continue;

            if (children.Count == 1)
            {
                var childTop = GetTopAnchor(children[0]);
                var childColor = EdgeStateColor(children[0]);
                if (Math.Abs(parentBottom.X - childTop.X) < 0.5f)
                {
                    handle.DrawLine(parentBottom, childTop, childColor);
                    continue;
                }

                var soloMidY = (parentBottom.Y + childTop.Y) / 2f;
                handle.DrawLine(parentBottom, new Vector2(parentBottom.X, soloMidY), trunkColor);
                handle.DrawLine(new Vector2(parentBottom.X, soloMidY), new Vector2(childTop.X, soloMidY), trunkColor);
                handle.DrawLine(new Vector2(childTop.X, soloMidY), childTop, childColor);
                continue;
            }

            var childTops = children.Select(GetTopAnchor).ToList();
            var busY = (parentBottom.Y + childTops[0].Y) / 2f;
            var minX = Math.Min(parentBottom.X, childTops.Min(c => c.X));
            var maxX = Math.Max(parentBottom.X, childTops.Max(c => c.X));

            handle.DrawLine(parentBottom, new Vector2(parentBottom.X, busY), trunkColor);
            handle.DrawLine(new Vector2(minX, busY), new Vector2(maxX, busY), trunkColor);

            for (var i = 0; i < children.Count; i++)
                handle.DrawLine(new Vector2(childTops[i].X, busY), childTops[i], EdgeStateColor(children[i]));
        }

        foreach (var tech in _techs)
        {
            var center = GetCenter(tech);
            var iconRadius = IconSize / 2;

            var matchesSearch = _filter.Length == 0 ||
                                 Loc.GetString(tech.Name).Contains(_filter, StringComparison.OrdinalIgnoreCase);
            var matchesDiscipline = _disciplineFilter == null || tech.Discipline == _disciplineFilter;
            var opacity = matchesSearch && matchesDiscipline ? 1f : 0.25f;

            var stateColor = LockedNodeColor;
            if (database.UnlockedTechnologies.Any(u => u.Id == tech.ID))
                stateColor = UnlockedNodeColor;
            else if (_research.IsTechnologyAvailable(database, tech))
                stateColor = AvailableNodeColor;
            var color = Fade(stateColor, opacity);

            var line = TruncateForPlate(Loc.GetString(tech.Name));
            var neededWidth = handle.GetDimensions(_font, line, 1).X;
            // floor at MinPlateWidth, but never shrink below what the (already-truncated) text needs
            var actualPlateWidth = Math.Max(neededWidth + 48 * UIScale * _zoom, MinPlateWidth);
            var plateBox = UIBox2.FromDimensions(
                new Vector2(center.X - actualPlateWidth / 2, center.Y + iconRadius + PlateGap),
                new Vector2(actualPlateWidth, PlateHeight));

            var hoveredIcon = (cursor - center).LengthSquared() <= iconRadius * iconRadius;
            var hoveredPlate = plateBox.Contains(cursor);
            var hovered = hoveredIcon || hoveredPlate;
            if (hovered)
                _hoveredTech = tech;

            if (hovered)
            {
                // glow radius = icon radius + an outward pad, same idea as the plate's glow -
                // it needs to actually clear the icon's own edge, or the opaque ring/disc drawn
                // right after this covers almost all of it and the glow reads as invisible
                var glowPad = 16 * UIScale * _zoom;
                var glowSize = (iconRadius + glowPad) * 2f;
                var glowBox = UIBox2.FromDimensions(center - new Vector2(glowSize / 2, glowSize / 2), new Vector2(glowSize, glowSize));
                handle.DrawTextureRect(_glowTexture, glowBox, HoverGlowColor.WithAlpha(0.45f));
                DrawSoftGlowRect(handle, plateBox, 6 * UIScale * _zoom);
            }

            var innerRadius = iconRadius - IconBorderThickness;
            var discBox = UIBox2.FromDimensions(center - new Vector2(innerRadius, innerRadius), new Vector2(innerRadius * 2, innerRadius * 2));
            handle.DrawTextureRect(_discTexture, discBox, Fade(PlateBackgroundColor, opacity));

            var artSize = innerRadius * 2 * 0.82f;
            var artBox = UIBox2.FromDimensions(center - new Vector2(artSize / 2, artSize / 2), new Vector2(artSize, artSize));
            handle.DrawTextureRect(_sprite.Frame0(tech.Icon), artBox, Color.White.WithAlpha(opacity));

            var ringBox = UIBox2.FromDimensions(center - new Vector2(iconRadius, iconRadius), new Vector2(iconRadius * 2, iconRadius * 2));
            handle.DrawTextureRect(_ringTexture, ringBox, color);

            DrawHSlicedRect(handle, _plateBgTexture, plateBox, Fade(PlateBackgroundColor, opacity));
            DrawHSlicedRect(handle, _plateRingTexture, plateBox, color);

            var lineDims = handle.GetDimensions(_font, line, 1);
            var linePos = new Vector2(plateBox.Center.X - lineDims.X / 2, plateBox.Center.Y - lineDims.Y / 2);
            handle.DrawString(_font, linePos, line, color);
        }
    }

    private static Color Fade(Color color, float opacity) => new(color.R, color.G, color.B, color.A * opacity);

    // Blueprint-grid canvas backdrop, tiled to cover the whole scrollable tree (not just the
    // visible viewport) so it stays put under the tree as you pan/zoom instead of looking like
    // a fixed wallpaper behind it. DrawTextureRect always stretches src->dest with no native
    // repeat mode, so tiling is just a manual grid of draw calls at a fixed on-screen tile size.
    private void DrawBlueprintBackground(DrawingHandleScreen handle, Vector2 origin)
    {
        var tileW = 480f * UIScale * _zoom;
        var tileH = tileW * ((float)_blueprintTexture.Height / _blueprintTexture.Width);
        var canvasW = Size.X * UIScale;
        var canvasH = Size.Y * UIScale;
        var cols = (int)Math.Ceiling(canvasW / tileW) + 1;
        var rows = (int)Math.Ceiling(canvasH / tileH) + 1;

        var tint = Color.White.WithAlpha(0.5f);
        for (var ty = 0; ty < rows; ty++)
        for (var tx = 0; tx < cols; tx++)
        {
            var tileBox = UIBox2.FromDimensions(origin + new Vector2(tx * tileW, ty * tileH), new Vector2(tileW, tileH));
            handle.DrawTextureRect(_blueprintTexture, tileBox, tint);
        }
    }

    // Horizontal 3-slice: the plate textures are a 128x40 rounded rect with a 10px corner radius.
    // Plate width varies per node (shrink-to-fit text), so a plain whole-texture stretch would
    // squash the rounded corners into ellipses - slice out the two corner caps at a fixed source
    // width and only stretch the flat middle strip, same idea as RT's own StyleBoxTexture 9-slice.
    private void DrawHSlicedRect(DrawingHandleScreen handle, Texture texture, UIBox2 destBox, Color modulate)
    {
        const float texW = 128f, texH = 40f, capPx = 13f;
        var destCap = Math.Min(capPx * UIScale * _zoom, destBox.Width / 2f);

        handle.DrawTextureRectRegion(texture,
            new UIBox2(destBox.Left, destBox.Top, destBox.Left + destCap, destBox.Bottom),
            new UIBox2(0, 0, capPx, texH), modulate);

        handle.DrawTextureRectRegion(texture,
            new UIBox2(destBox.Right - destCap, destBox.Top, destBox.Right, destBox.Bottom),
            new UIBox2(texW - capPx, 0, texW, texH), modulate);

        if (destBox.Width > destCap * 2)
        {
            handle.DrawTextureRectRegion(texture,
                new UIBox2(destBox.Left + destCap, destBox.Top, destBox.Right - destCap, destBox.Bottom),
                new UIBox2(texW / 2f - 1, 0, texW / 2f + 1, texH), modulate);
        }
    }

    // Uses the same rounded plate texture as the plate itself (via DrawHSlicedRect), not a plain
    // DrawRect - a sharp-cornered glow behind a rounded plate reads as a visible square outline.
    private void DrawSoftGlowRect(DrawingHandleScreen handle, UIBox2 box, float extra)
    {
        const int steps = 3;
        for (var step = steps; step >= 1; step--)
        {
            var frac = step / (float)steps;
            var pad = extra * frac;
            var alpha = 0.05f + 0.14f * (1f - frac);
            var glowBox = new UIBox2(box.Left - pad, box.Top - pad, box.Right + pad, box.Bottom + pad);
            DrawHSlicedRect(handle, _plateBgTexture, glowBox, HoverGlowColor.WithAlpha(alpha));
        }
    }

    // Single line only - a plate tall enough for 2 lines but usually showing 1 looked lopsided
    // (that was the real "boxes look uneven" issue, not padding). Long names get ellipsis-truncated
    // instead of wrapping; the full name is always available in the detail panel on click.
    // Character-count truncation (like HOI4's focus names), not pixel-width - a fixed budget in
    // characters reads consistently across names instead of cutting some names much shorter than
    // others just because their glyphs happen to be a bit wider on average.
    private static string TruncateForPlate(string text)
    {
        if (text.Length <= PlateMaxChars)
            return text;

        return text[..(PlateMaxChars - 1)] + "…";
    }
}
