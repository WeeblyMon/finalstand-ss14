    public FieldKitStationWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ((Control) this).Stylesheet = FSMenuStylesheet.Get(IoCManager.Resolve<IUserInterfaceManager>(), _res);

        _caption = _res.NotoStack("Bold", 9);
        _body = _res.NotoStack("Regular", 11);
        _bold = _res.NotoStack("Bold", 11);
