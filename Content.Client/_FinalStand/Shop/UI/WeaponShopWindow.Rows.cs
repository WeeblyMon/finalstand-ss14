    // Row fills for the three upgrade states. Window-local: they tint a row, they do not carry
    // meaning on their own - the palette border beside each one does that.
    private static readonly Color RowInactive = Color.FromHex("#0F0F13");
    private static readonly Color RowMaxed    = Color.FromHex("#0C1A0C");
    private static readonly Color RowOwned    = Color.FromHex("#151A2E");

    private BoxContainer BuildStatBar(string label, float fill, string numericText,
        Color? valueColor = null, string? valueTooltip = null)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 0, 0, 6),
            VerticalAlignment = VAlignment.Center,
        };

        row.AddChild(new Label
        {
            Text = label,
            SetWidth = 98,
            Modulate = FSUiPalette.TextMuted,
        });

        var clamped = Math.Max(0f, Math.Min(1f, fill));
        var filled  = (int)Math.Round(clamped * BarSegments);
        var barColor = StatBarColor((int)(clamped * 100f));

        var segBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };

        var segments = new PanelContainer[BarSegments];
        for (var i = 0; i < BarSegments; i++)
        {
            var seg = new PanelContainer
            {
                HorizontalExpand = true,
                SetHeight = 10,
                Margin = new Thickness(i == 0 ? 0 : 1, 0, 0, 0),
            };
            seg.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = i < filled ? barColor : FSUiPalette.BgTrack,
            };
            segments[i] = seg;
            segBox.AddChild(seg);
        }
        row.AddChild(segBox);

        var valueLabel = new Label
        {
            Text = numericText,
            SetWidth = 72,
            Margin = new Thickness(7, 0, 0, 0),
            HorizontalAlignment = HAlignment.Right,
            Modulate = valueColor ?? FSUiPalette.TextMuted,
            MouseFilter = string.IsNullOrEmpty(valueTooltip) ? MouseFilterMode.Ignore : MouseFilterMode.Stop,
        };
        if (!string.IsNullOrEmpty(valueTooltip))
            valueLabel.ToolTip = valueTooltip;
        row.AddChild(valueLabel);

        _statBarRefs[label] = new StatBarRefs
        {
            Segments  = segments,
            ValueLabel = valueLabel,
            BaseFill  = fill,
            BaseText  = numericText,
            BaseColor = valueColor,
        };

        return row;
    }


    private Control BuildUpgradeRow(WeaponUpgradeDef def, int currentLevel, int credits, string name, string description, string? label = null)
    {
        var atMax     = currentLevel >= def.MaxLevel;
        var nextCost  = def.BaseCost * (currentLevel + 1);
        var canAfford = !def.IsStub && !atMax && credits >= nextCost;
        var hasAny    = currentLevel > 0;

        Color bgColor, borderColor;
        if (def.IsStub || (!canAfford && !atMax))
        {
            bgColor = RowInactive; borderColor = FSUiPalette.BorderNeutral;
        }
        else if (atMax)
        {
            bgColor = RowMaxed; borderColor = FSUiPalette.StatePositive;
        }
        else if (hasAny)
        {
            bgColor = RowOwned; borderColor = FSUiPalette.AccentBrand;
        }
        else
        {
            bgColor = FSUiPalette.BgSurface; borderColor = FSUiPalette.BorderNeutral;
        }

        var card = new PanelContainer { Margin = new Thickness(0, 2, 0, 2) };
        card.PanelOverride = MakeCardStyle(bgColor, borderColor);
        card.MouseFilter = MouseFilterMode.Pass;

        var inner = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(6, 4, 6, 4),
            VerticalAlignment = VAlignment.Center,
        };

        var btn = new Button
        {
            Text = name,
            MinWidth = 140,
            MaxWidth = 185,
            ClipText = true,
            Disabled = def.IsStub || atMax || !canAfford,
            ToolTip = string.IsNullOrEmpty(description) ? name : description,
        };
        btn.OnPressed += _ => OnUpgradePressed?.Invoke(def.Id);
        inner.AddChild(btn);

        if (def.IsStub)
        {
            btn.Disabled = true;
            btn.ToolTip = "Not yet implemented.";
            inner.AddChild(new Label
            {
                Text = "WIP",
                Modulate = FSUiPalette.StateNegative,
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Right,
            });
            card.AddChild(inner);
            card.Modulate = new Color(1f, 1f, 1f, FSUiPalette.DisabledOpacity);
            return card;
        }

        // Button + card hover both wired so the whole row reacts regardless of deepest mouse focus.
        if (!atMax)
        {
            btn.OnMouseEntered  += _ => SetHoveredUpgrade(def);
            btn.OnMouseExited   += _ => ClearPreview();
            card.OnMouseEntered += _ => SetHoveredUpgrade(def);
            card.OnMouseExited  += _ => ClearPreview();
        }

        var catText = label ?? UpgradeTypeToStatLabel(def.Type);
        if (!string.IsNullOrEmpty(catText))
        {
            var catLabel = new Label
            {
                Text = catText,
                Modulate = FSUiPalette.TextMuted,
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Left,
                Margin = new Thickness(4, 0, 0, 0),
                MouseFilter = MouseFilterMode.Pass,
            };
            if (!atMax)
            {
                catLabel.OnMouseEntered += _ => SetHoveredUpgrade(def);
                catLabel.OnMouseExited  += _ => ClearPreview();
            }
            inner.AddChild(catLabel);
        }
        else
        {
            inner.AddChild(new Control { HorizontalExpand = true });
        }

        if (def.MaxLevel <= 5)
        {
            var pips = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(4, 0, 4, 0),
                VerticalAlignment = VAlignment.Center,
            };
            for (var i = 0; i < def.MaxLevel; i++)
            {
                var pip = new Label
                {
                    Text = "■",
                    Modulate = i < currentLevel
                        ? (atMax ? FSUiPalette.StatePositive : FSUiPalette.AccentBrand)
                        : FSUiPalette.BgTrack,
                    MouseFilter = MouseFilterMode.Pass,
                };
                if (!atMax)
                {
                    pip.OnMouseEntered += _ => SetHoveredUpgrade(def);
                    pip.OnMouseExited  += _ => ClearPreview();
                }
                pips.AddChild(pip);
            }
            inner.AddChild(pips);
        }
        else
        {
            var levelColor = atMax ? FSUiPalette.StatePositive
                : currentLevel > 0 ? FSUiPalette.AccentBrand
                : FSUiPalette.TextMuted;
            var levelText = new Label
            {
                Text = $"{currentLevel}/{def.MaxLevel}",
                Modulate = levelColor,
                MinWidth = 40,
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(4, 0, 4, 0),
                MouseFilter = MouseFilterMode.Pass,
            };
            if (!atMax)
            {
                levelText.OnMouseEntered += _ => SetHoveredUpgrade(def);
                levelText.OnMouseExited  += _ => ClearPreview();
            }
            inner.AddChild(levelText);
        }

        var priceLabel = new Label
        {
            Text = atMax ? "MAX" : $"${nextCost:N0}",
            Modulate = atMax
                ? FSUiPalette.StatePending
                : canAfford ? FSUiPalette.StatePositive : FSUiPalette.StateNegative,
            MinWidth = 72,
            HorizontalAlignment = HAlignment.Right,
            Margin = new Thickness(0, 0, 4, 0),
            MouseFilter = MouseFilterMode.Pass,
        };
        if (!atMax)
        {
            priceLabel.OnMouseEntered += _ => SetHoveredUpgrade(def);
            priceLabel.OnMouseExited  += _ => ClearPreview();
        }
        inner.AddChild(priceLabel);

        card.AddChild(inner);

        if (!canAfford && !atMax)
            card.Modulate = new Color(1f, 1f, 1f, FSUiPalette.DisabledOpacity);

        return card;
    }

    private static StyleBoxFlat MakeCardStyle(Color bg, Color border) => new()
    {
        BackgroundColor = bg,
        BorderColor = border,
        BorderThickness = new Thickness(1),
    };


