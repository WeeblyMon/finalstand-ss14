namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    [Dependency] private readonly IEntityManager _entManager = default!;

    public Button CharacterSetupButton => CharacterSetup;

    private EntityUid? _previewDummy;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    /// FS: ported from Goob — LobbyUIController.RefreshLobbyPreview calls this with the preview dummy entity.
    public void SetSprite(EntityUid uid)
    {
        if (_previewDummy != null)
            _entManager.DeleteEntity(_previewDummy);

        _previewDummy = uid;

        ViewBox.DisposeAllChildren();
        var spriteView = new SpriteView
        {
            OverrideDirection = Direction.South,
            Scale = new Vector2(4f, 4f),
            MaxSize = new Vector2(112, 112),
            Stretch = SpriteView.StretchMode.Fill,
        };
        spriteView.SetEntity(uid);
        ViewBox.AddChild(spriteView);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (disposing && _previewDummy != null)
        {
            _entManager.DeleteEntity(_previewDummy);
            _previewDummy = null;
        }
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    public void SetSummaryText(string value)
    {
        // Put the name and the age on separate lines ("This is X.\nThey are Y years old.")
        var idx = value.IndexOf(". ", StringComparison.Ordinal);
        Summary.Text = idx >= 0 ? value[..(idx + 1)] + "\n" + value[(idx + 2)..] : value;
    }

    public void SetAugmentPointsText(int augmentPoints)
    {
        PerkPointsLabel.Text = $"Perk Points: {augmentPoints:N0}";
    }

    // FINALSTAND: leveling display
    public Button AugmentShopButtonControl => AugmentShopButton;
    public Button PrestigeButtonControl => PrestigeButton;

    public void SetLevelText(string text) => LevelLabel.Text = text;
    public void SetXpText(string text) => XpLabel.Text = text;
    public void SetPrestigeButtonVisible(bool visible) => PrestigeButton.Visible = visible;
}
