    public FSResearchTreeMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _research = _entity.System<ResearchSystem>();
        _fsResearch = _entity.System<FSResearchClientSystem>();
        _materialStorage = _entity.System<SharedMaterialStorageSystem>();

        ((Control) this).Stylesheet = FSMenuStylesheet.Get(IoCManager.Resolve<IUserInterfaceManager>(), _resourceCache);

        _captionFont = _resourceCache.NotoStack("Bold", 9);
